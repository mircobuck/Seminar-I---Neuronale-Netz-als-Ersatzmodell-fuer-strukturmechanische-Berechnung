function writeIntegration(folder)
%WRITEINTEGRATION Only reads saved results; does not run FEM or train.
e=load(fullfile(folder,'frequency_evaluation.mat')); e=e.result;
m=load(fullfile(folder,'frequency_model.mat')); m=m.result;
d=load(fullfile(folder,'density_check.mat')); d=d.result;
s=load(fullfile(folder,'static_integration.mat')); s=s.result;
file=fullfile(folder,'integration_report.tex'); fid=fopen(file,'w','n','UTF-8');
assert(fid>=0); clean=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s\n','\documentclass[11pt,a4paper]{article}', ...
    '\usepackage{fontspec,amsmath,booktabs,geometry}', ...
    '\usepackage[ngerman]{babel}', ...
    '\geometry{margin=25mm}', ...
    '\title{FEM-Ersatzmodelle: erster Integrationsnachweis}', ...
    '\author{Versionierte Migration, Phase 1}', ...
    '\begin{document}\maketitle', ...
    '\section{Umfang und Daten}', ...
    'Kleiner Integrationslauf mit 12 Trainings-, sechs Validierungs- und sechs Testfällen. Sechs Moden eines Falles sind keine unabhängigen Parameterfälle. Die historische Studie bleibt unverändert. Dichte: 7850 kg/m$^3$ als Demonstrationsannahme.', ...
    '\section{Modal-FEM und Netzkonvergenz}', ...
    'Unbelasteter, ungedämpfter Kragkörper; Eigenfrequenzen in Hz. Drei Parameterfälle wurden auf drei Netzstufen untersucht. Die folgende Tabelle zeigt die größte relative Änderung der ersten sechs zugeordneten Frequenzen zwischen den beiden feinsten Stufen.');
fprintf(fid,'%s\n','\begin{center}\begin{tabular}{lrr}\toprule Fall & Max. Änderung & Bestanden \\ \midrule');
for i=[1 6 12]
    a=load(fullfile(folder,sprintf('comparison_%02d.mat',i))); c=a.result;
    line=sprintf('%d & %.4f',i,100*max(c.relativeFrequency(1:6)))+"\,\% & "+string(c.pass)+" \\";
    fprintf(fid,'%s\n',line);
end
fprintf(fid,'%s\n','\bottomrule\end{tabular}\end{center}', ...
    'Die 1\%-Abstandsregel ist eine Clusterheuristik. Eigenformen werden auf ein gemeinsames Abfragegitter übertragen; Cluster werden durch Unterraumvergleiche und Rangprüfung beurteilt.', ...
    '\section{Frequenz-GPR}', ...
    'Zwei Kernel wurden nur mit Trainingsdaten angepasst. Die Validierung wählt den Kandidaten; die eingefrorene Auswahl wird anschließend auf dem Test ausgewertet. Die Aufgabe ist das aufsteigend sortierte Spektrum, keine Zuordnung physikalischer Modenfamilien.', ...
    '\[ e_{ij}=\frac{|\widehat f_{ij}-f_{ij}|}{|f_{ij}|},\qquad f_i>10^{-8}\,\mathrm{Hz}. \]');
line="Gewählter Kernel: \texttt{"+m.kernel+"}. Validierungsfehler: "+sprintf('%.3f',100*m.validationScores(1))+"\,\% und "+sprintf('%.3f',100*m.validationScores(2))+"\,\%.";
fprintf(fid,'%s\n',line);
line="Mittlerer relativer Testfehler vor Sortierung: "+sprintf('%.3f',100*mean(e.metrics.relativeRaw,'all'))+"\,\%; nach Sortierung: "+sprintf('%.3f',100*mean(e.metrics.relativeSorted,'all'))+"\,\%. Reihenfolgeverletzung: "+sprintf('%.1f',100*e.metrics.orderViolationFraction)+"\,\% der Testfälle.";
fprintf(fid,'%s\n',line);
fprintf(fid,'%s\n','\section{Physikalische und technische Prüfungen}');
fprintf(fid,'%s\n',"Dichtetest bei unverändertem Netz: maximale relative Abweichung von $1/\sqrt{2}$ "+sprintf('%.3g',d.maxRelativeDeviation)+".");
fprintf(fid,'Acht historische statische Adapter: maximaler Unterschied zur direkten Vorhersage %.3g. POD-Galerkin wurde an einem Fall verglichen, die übrigen Modelle an sechs Fällen.\n',max(structfun(@(x)x.maximumDifference,s)));
fprintf(fid,'%s\n','Die gewichtete Feldnorm verwendet Trapezgewichte mit Summe eins je Komponente und trägt bei Verschiebungen die Einheit Meter. Der Integrationslauf ist keine belastbare Lernkurve. Offene Arbeiten und die unabhängige größere Studienplanung sind in der Architekturdatei dokumentiert.', ...
    '\end{document}');
end
