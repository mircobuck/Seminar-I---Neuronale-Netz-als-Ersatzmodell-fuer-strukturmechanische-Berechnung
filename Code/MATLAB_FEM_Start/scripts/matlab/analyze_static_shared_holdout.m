function analyze_static_shared_holdout()
%ANALYZE_STATIC_SHARED_HOLDOUT Verify and explain the frozen 64-case result.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
cfg=jsondecode(fileread(fullfile(root,'configs', ...
    'static_shared_comparison_20261028_v1.json')));
out=fullfile(root,'experiments','active',cfg.study);
evaluation=load(fullfile(out,'final_evaluation.mat'),'value');
value=evaluation.value;
assert(value.mode=="final" && numel(value.testIDs)==64, ...
    'femstudy:shared:IncompleteFinalTest','Final evaluation is not the complete 64-case test.');
assert(height(value.summaryByModelSeed)==9 && ...
    height(value.caseMetrics)==64*9 && ...
    height(value.pairedCaseDifferences)==nchoosek(9,2)*64 && ...
    height(value.predictionTimings)==9*64*cfg.timing.predictionRepeatsPerCase, ...
    'femstudy:shared:IncompleteModelCaseGrid', ...
    'Final model/seed/case, paired, or timing rows are incomplete.');
assert(all(isfinite(value.caseMetrics.RelativeWeightedFieldError)) && ...
    all(isfinite(value.caseMetrics.AbsoluteWeightedRMS_m)) && ...
    all(isfinite(value.caseMetrics.PredictionMedianSeconds)), ...
    'femstudy:shared:MissingMetrics','Final evaluation contains missing or nonfinite metrics.');
assert(height(unique(value.caseMetrics(:,{'Model','Seed','TestID'})))==576, ...
    'femstudy:shared:DuplicateMetricKey','Duplicate or missing model/seed/case keys.');
assert(isequal(sort(unique(value.caseMetrics.TestID)),sort(value.testIDs(:))), ...
    'femstudy:shared:MetricCaseIDs','Final metric case IDs differ from sealed IDs.');

for i=1:height(value.summaryByModelSeed)
    row=value.summaryByModelSeed(i,:);
    selected=value.caseMetrics.Model==row.Model & ...
        value.caseMetrics.Seed==row.Seed;
    errors=sort(value.caseMetrics.RelativeWeightedFieldError(selected));
    absolute=sort(value.caseMetrics.AbsoluteWeightedRMS_m(selected));
    assert(numel(errors)==64 && ...
        closeEnough(row.MedianRelative,median(errors)) && ...
        closeEnough(row.P95Relative,errors(ceil(.95*numel(errors)))) && ...
        closeEnough(row.MaxRelative,max(errors)) && ...
        closeEnough(row.MedianAbsoluteRMS_m,median(absolute)) && ...
        closeEnough(row.P95AbsoluteRMS_m,absolute(ceil(.95*numel(absolute)))) && ...
        closeEnough(row.MaxAbsoluteRMS_m,max(absolute)), ...
        'femstudy:shared:SummaryMismatch', ...
        'Summary aggregation does not match case rows for %s seed %d.', ...
        row.Model,row.Seed);
end

prepared=load(fullfile(out,'prepared.mat'),'value');
prepared=prepared.value;
train=load(fullfile(root,cfg.trainingSource,'train.mat'),'D');
val=load(fullfile(root,cfg.trainingSource,'val.mat'),'D');
known=load(fullfile(root,cfg.trainingSource,'test.mat'),'D');
assert(isequal(prepared.trainIDs,train.D.id(:)) && ...
    isequal(prepared.validationIDs,val.D.id(:)) && ...
    isequal(prepared.knownTestIDs,known.D.id(:)) && ...
    isempty(intersect(prepared.holdoutIDs, ...
    [train.D.id(:);val.D.id(:);known.D.id(:)])), ...
    'femstudy:shared:SplitOverlap','Holdout overlaps train, validation, or known test IDs.');
assert(isequal(value.testIDs(:),prepared.holdoutIDs(:)), ...
    'femstudy:shared:FinalIDMismatch','Final evaluation IDs differ from sealed holdout.');

caseDir=fullfile(out,'holdout_cases');
referenceFiles=strings(64,1); X=prepared.holdoutX;
for i=1:64
    [referenceFiles(i),reference]=findSuccessfulReference(caseDir, ...
        prepared.holdoutIDs(i),X(i,:),cfg.fieldPointCount);
    if i==1, xi=reference.xi; w=reference.w(:); end
    assert(isequal(reference.xi,xi) && isequal(reference.w(:),w), ...
        'femstudy:shared:FinalGridMismatch','Final FEM grids differ between cases.');
    assert(all(isfinite(reference.S)) && numel(reference.S)==3*cfg.fieldPointCount, ...
        'femstudy:shared:FinalFieldInvalid','Final FEM field is incomplete or nonfinite.');
end
assert(numel(unique(referenceFiles))==64, ...
    'femstudy:shared:ReferenceFileDuplicate','A reference artifact was reused for multiple IDs.');

diagnosticRows=cell(9,23);
for k=1:height(value.summaryByModelSeed)
    summary=value.summaryByModelSeed(k,:);
    rows=value.caseMetrics.Model==summary.Model & ...
        value.caseMetrics.Seed==summary.Seed;
    these=value.caseMetrics(rows,:);
    [~,worstRow]=max(these.RelativeWeightedFieldError);
    caseID=these.TestID(worstRow);
    index=find(prepared.holdoutIDs==caseID,1);
    [~,reference]=findSuccessfulReference(caseDir,caseID,X(index,:),cfg.fieldPointCount);
    H=predictFrozenModel(out,summary.Model,summary.Seed,reference.x,xi);
    metric=femstudy.metrics.field(reference.S(:),H(:),w,reference.x);
    errorField=H(:)-reference.S(:);
    n=cfg.fieldPointCount;
    componentAbsolute=metric.componentAbsolute(1,:);
    componentRelative=metric.componentRelative(1,:);
    fieldBlocks=reshape(errorField,n,3);
    pointError=sqrt(sum(fieldBlocks.^2,2));
    [maxPointError,pointIndex]=max(pointError);
    diagnosticRows(k,:)={summary.Model,summary.Seed,caseID, ...
            summary.MedianRelative,these.RelativeWeightedFieldError(worstRow), ...
        summary.MedianAbsoluteRMS_m, ...
        X(index,1),X(index,2),X(index,3),X(index,4),X(index,5),X(index,6), ...
        componentAbsolute(1),componentAbsolute(2),componentAbsolute(3), ...
        componentRelative(1),componentRelative(2),componentRelative(3), ...
        maxPointError,xi(1,pointIndex),xi(2,pointIndex),xi(3,pointIndex), ...
        string(referenceFiles(index))};
end
diagnostics=cell2table(diagnosticRows,'VariableNames', ...
    {'Model','Seed','WorstTestID','ModelMedianRelative','WorstRelative', ...
    'ModelMedianAbsoluteRMS_m','L_m','b_m','h_m','E_Pa','nu','Fz_N', ...
    'WorstUxAbsoluteRMS_m','WorstUyAbsoluteRMS_m','WorstUzAbsoluteRMS_m', ...
    'WorstUxRelative','WorstUyRelative','WorstUzRelative', ...
    'MaxPointwiseVectorError_m','MaxPointXi_x','MaxPointXi_y','MaxPointXi_z', ...
    'ReferenceArtifact'});
writeAnalysisTable(fullfile(out,'independent_holdout_worst_cases.csv'),diagnostics);

timing=value.predictionTimings;
caseMedians=unique(timing(:,{'Model','Seed','TestID','CaseMedianSeconds'}));
[caseGroups,caseModels,caseSeeds]=findgroups(caseMedians.Model,caseMedians.Seed);
perModelMedian=splitapply(@median,caseMedians.CaseMedianSeconds,caseGroups);
perModelP95=splitapply(@(x)nearestRank(x,.95),caseMedians.CaseMedianSeconds,caseGroups);
perModelMax=splitapply(@max,caseMedians.CaseMedianSeconds,caseGroups);
training=unique(value.caseMetrics(:,{'Model','Seed','TrainingSeconds'}));
costs=outerjoin(table(caseModels,caseSeeds,perModelMedian,perModelP95,perModelMax, ...
    'VariableNames',{'Model','Seed','MedianCasePredictionSeconds', ...
    'P95CasePredictionSeconds','MaxCasePredictionSeconds'}), ...
    training,'Keys',{'Model','Seed'},'MergeKeys',true,'Type','left');
costs=sortrows(costs,{'Model','Seed'});
writeAnalysisTable(fullfile(out,'independent_holdout_prediction_costs.csv'),costs);

pair=value.pairedCaseDifferences;
[pairGroups,modelA,seedA,modelB,seedB]=findgroups( ...
    pair.ModelA,pair.SeedA,pair.ModelB,pair.SeedB);
pairSummary=table(modelA,seedA,modelB,seedB, ...
    splitapply(@median,pair.AminusBRelativeError,pairGroups), ...
    splitapply(@(x)nearestRank(x,.95),abs(pair.AminusBRelativeError),pairGroups), ...
    splitapply(@(x)mean(x>0),pair.AminusBRelativeError,pairGroups), ...
    splitapply(@numel,pair.AminusBRelativeError,pairGroups), ...
    'VariableNames',{'ModelA','SeedA','ModelB','SeedB', ...
    'MedianAminusBRelativeError','P95AbsolutePairedDifference', ...
    'FractionCasesA_WorseThanB','PairedCases'});
writeAnalysisTable(fullfile(out,'independent_holdout_paired_summary.csv'),pairSummary);

femSeconds=unique(value.predictionTimings(:,{'TestID','ReferenceFEMSeconds'}));
assert(height(femSeconds)==64 && all(isfinite(femSeconds.ReferenceFEMSeconds)), ...
    'femstudy:shared:FEMTimingIncomplete','Reference FEM timings are incomplete or duplicated.');
femCost=table(height(femSeconds),sum(femSeconds.ReferenceFEMSeconds), ...
    median(femSeconds.ReferenceFEMSeconds), ...
    nearestRank(femSeconds.ReferenceFEMSeconds,.95), ...
    max(femSeconds.ReferenceFEMSeconds), ...
    'VariableNames',{'SuccessfulCases','TotalFEMSeconds','MedianFEMSeconds', ...
    'P95FEMSeconds','MaxFEMSeconds'});
writeAnalysisTable(fullfile(out,'independent_holdout_fem_cost.csv'),femCost);

failed=dir(fullfile(caseDir,'case_*_attempt_*.mat'));
initialFailed=fullfile(caseDir,'case_700001.mat');
assert(isfile(initialFailed),'femstudy:shared:FailureLedgerMissing', ...
    'Expected preserved first-attempt runner failure record is missing.');
failure=load(initialFailed,'value');
assert(failure.value.status=="failed" && failure.value.id==700001 && ...
    failure.value.errorIdentifier=="MATLAB:undefinedVarOrClass", ...
    'femstudy:shared:FailureLedgerChanged','Preserved first-attempt failure record changed.');
fprintf('Verified 576 unique metrics, 2304 paired rows, 4032 timing rows, and 64 successful FEM references.\n');
fprintf('Retained failed attempts: initial failure for ID 700001; successful retry file count=%d.\n', ...
    numel(failed));
disp(diagnostics(:,{'Model','Seed','WorstTestID','WorstRelative', ...
    'L_m','b_m','h_m','E_Pa','nu','Fz_N','WorstUxRelative', ...
    'WorstUyRelative','WorstUzRelative','MaxPointwiseVectorError_m'}));
disp(costs);
disp(femCost);
end

function [path,value]=findSuccessfulReference(caseDir,id,X,fieldPointCount)
base=sprintf('case_%06d',id);
attempts=dir(fullfile(caseDir,[base '_attempt_*.mat']));
files=[string(fullfile(caseDir,[base '.mat'])); ...
    string(fullfile({attempts.folder}',{attempts.name}'))];
path=""; value=[];
for i=1:numel(files)
    if ~isfile(files(i)), continue; end
    a=load(files(i),'value'); candidate=a.value;
    assert(candidate.id==id && isequal(candidate.x,X), ...
        'femstudy:shared:FinalLabelMismatch','Reference artifact ID/parameters conflict.');
    if candidate.status=="success"
        assert(path=="",'femstudy:shared:DuplicateSuccessfulReference', ...
            'Multiple successful labels exist for ID %d.',id);
        path=files(i); value=candidate;
    end
end
assert(path~="",'femstudy:shared:FinalLabelMissing', ...
    'No successful reference label exists for ID %d.',id);
assert(numel(value.S)==3*fieldPointCount && all(isfinite(value.S)), ...
    'femstudy:shared:FinalFieldInvalid','Reference field incomplete for ID %d.',id);
end

function H=predictFrozenModel(out,id,seed,X,xi)
switch id
    case "Beam_theory_field"
        H=femstudy.fem.beamField(X,xi);
    case "POD_MLP"
        a=load(fullfile(out,'models',"neural_pod_seed"+seed+".mat"),'value');
        H=femstudy.models.predictNeural(a.value.model,X);
    case "Beam_Residual_MLP"
        a=load(fullfile(out,'models',"neural_residual_seed"+seed+".mat"),'value');
        H=femstudy.models.predictNeural(a.value.model,X);
    case "POD_GPR"
        a=load(fullfile(out,'models','pod_gpr.mat'),'value');
        m=a.value.model; H=m.pod.mean+m.pod.V*predict_reg(m.reg,X)';
    case "Beam_Field_POD_GPR"
        a=load(fullfile(out,'models','beam_residual_gpr.mat'),'value');
        p=femstudy.models.predictBeamField(a.value.model,X); H=p.field;
    otherwise
        error('femstudy:shared:UnknownModel','Unknown frozen model: %s',id);
end
assert(size(H,1)==3*size(xi,2) && all(isfinite(H),'all'), ...
    'femstudy:shared:DiagnosticPrediction','Invalid diagnostic prediction.');
end

function tf=closeEnough(a,b)
tf=abs(a-b)<=1e-11*max(1,abs(b));
end

function value=nearestRank(x,p)
x=sort(x(isfinite(x)));
value=x(max(1,ceil(p*numel(x))));
end

function writeAnalysisTable(path,expected)
if ~isfile(path)
    writetable(expected,path);
    return
end
actual=readtable(path,TextType="string");
assert(isequal(actual.Properties.VariableNames,expected.Properties.VariableNames) && ...
    height(actual)==height(expected), ...
    'femstudy:shared:AnalysisOutputConflict', ...
    'Existing analysis output has a different shape/schema: %s',path);
for i=1:width(expected)
    a=actual{:,i}; b=expected{:,i};
    if isnumeric(a) && isnumeric(b)
        assert(isequal(size(a),size(b)) && ...
            all(abs(a(:)-b(:))<=1e-12*max(1,max(abs(b(:))))), ...
            'femstudy:shared:AnalysisOutputConflict', ...
            'Existing analysis output differs from recomputed values: %s',path);
    elseif ~isequaln(a,b)
        error('femstudy:shared:AnalysisOutputConflict', ...
            'Existing analysis output differs from recomputed values: %s',path);
    end
end
end
