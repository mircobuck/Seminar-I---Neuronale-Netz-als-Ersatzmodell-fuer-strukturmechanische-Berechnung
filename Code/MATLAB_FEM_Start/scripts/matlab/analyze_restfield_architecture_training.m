function analyze_restfield_architecture_training()
%ANALYZE_RESTFIELD_ARCHITECTURE_TRAINING Audit stored CV runs without refitting.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
cfg=jsondecode(fileread(fullfile(root,'configs', ...
    'restfield_mlp_architecture_training_20261028_v1.json')));
out=fullfile(root,'experiments','active',cfg.study);
preparedFile=fullfile(out,'prepared.mat');
assert(isfile(preparedFile),'femstudy:restfieldStudy:PreparedMissing', ...
    'Prepared fold manifest is missing.');
revisions=dir(fullfile(out,'prepared_revision_*.mat'));
if ~isempty(revisions)
    [~,order]=sort({revisions.name});
    loaded=load(fullfile(out,revisions(order(end)).name),'value');
else
    loaded=load(preparedFile,'value');
end
prepared=loaded.value;
manifestFiles=[dir(fullfile(out,'prepared.mat'));dir(fullfile(out,'prepared_revision_*.mat'))];
acceptedCodeHashes=strings(numel(manifestFiles)+1,1);
for i=1:numel(manifestFiles)
    manifest=load(fullfile(manifestFiles(i).folder,manifestFiles(i).name),'value');
    acceptedCodeHashes(i)=combinedCodeHash(manifest.value.provenance);
end
acceptedCodeHashes(end)=combinedCodeHash(prepared.provenance);
acceptedCodeHashes=unique(acceptedCodeHashes,'stable');
assert(strcmp(prepared.provenance.configSHA256,sha256File(fullfile(root,'configs', ...
    'restfield_mlp_architecture_training_20261028_v1.json'))) && ...
    strcmp(prepared.provenance.trainingDataSHA256,sha256File(fullfile(root,cfg.source))), ...
    'femstudy:restfieldStudy:ProvenanceMismatch','Config or data hash differs from preparation.');
for i=1:numel(prepared.provenance.codePaths)
    path=fullfile(root,prepared.provenance.codePaths(i));
    assert(isfile(path) && strcmp(sha256File(path),prepared.provenance.codeSHA256(i)), ...
        'femstudy:restfieldStudy:CodeHashMismatch', ...
        'Code hash differs from preparation: %s',path);
end
folds=prepared.folds;
assert(height(folds)==384 && isequal(sort(unique(folds.Fold)),(1:3)') && ...
    numel(unique(folds.ID))==384,'femstudy:restfieldStudy:FoldDesignInvalid', ...
    'Fold manifest is incomplete or has duplicate IDs.');
assert(all(prepared.foldCounts==128), ...
    'femstudy:restfieldStudy:FoldBalance','Expected three balanced 128-case validation folds.');
for f=1:3
    prep=load(fullfile(out,'preprocessing',sprintf('fold_%02d.mat',f)),'value');
    value=prep.value;
    assert(numel(value.trainIDs)==256 && numel(value.validationIDs)==128 && ...
        isempty(intersect(value.trainIDs,value.validationIDs)) && ...
        isequal(sort(value.validationIDs),sort(folds.ID(folds.Fold==f))) && ...
        value.podRank<=cfg.pod.maximumRank && ...
        size(value.pod.V,2)==value.podRank && ...
        all(isfinite(value.trainCoefficients),'all') && ...
        all(isfinite(value.validationCoefficients),'all'), ...
        'femstudy:restfieldStudy:FoldArtifactInvalid','Invalid fold %d preprocessing.',f);
end

ledger=readAttemptLedger(fullfile(out,'attempt_ledger.csv'));
assert(all(ismember(ledger.Status,["completed","failed","aborted","running","planned"])), ...
    'femstudy:restfieldStudy:UnknownAttemptStatus','Ledger contains an unknown status.');
assert(numel(unique(ledger.RunID))==height(ledger), ...
    'femstudy:restfieldStudy:DuplicateRunID','Attempt ledger has duplicate RunIDs.');
completed=ledger(ledger.Status=="completed",:);
assert(all(cellfun(@isfile,cellstr(completed.Artifact))), ...
    'femstudy:restfieldStudy:AttemptArtifactMissing','Completed attempt artifact is missing.');
for i=1:height(completed)
    artifact=load(completed.Artifact(i),'value');
    assert(artifact.value.status=="completed" && ...
        artifact.value.runID==completed.RunID(i) && ...
        strcmp(artifact.value.metadata.configSHA256,prepared.provenance.configSHA256) && ...
        strcmp(artifact.value.metadata.dataSHA256,prepared.provenance.trainingDataSHA256), ...
        'femstudy:restfieldStudy:AttemptArtifactMismatch', ...
        'Ledger and run artifact disagree for %s.',completed.RunID(i));
    assert(any(acceptedCodeHashes==artifact.value.metadata.codeSHA256), ...
        'femstudy:restfieldStudy:AttemptCodeHashMismatch', ...
        'Run code hash is absent from the immutable provenance history: %s.',completed.RunID(i));
end

metrics=readtable(fullfile(out,'cross_validation_case_metrics.csv'),TextType="string");
assert(height(metrics)==(27+9+3)*128 && ...
    height(unique(metrics(:,{'RunID','CaseID'})))==height(metrics) && ...
    all(isfinite(metrics.RelativeWeightedFieldError)) && ...
    all(isfinite(metrics.AbsoluteWeightedRMS_m)) && ...
    all(isfinite(metrics.PODProjectionRelativeError)), ...
    'femstudy:restfieldStudy:MetricGridInvalid', ...
    'Cross-validation case metrics are incomplete, duplicated, or nonfinite.');
for i=1:height(metrics)
    fold=metrics.Fold(i);     id=metrics.CaseID(i);
    assert(any(folds.ID==id & folds.Fold==fold), ...
        'femstudy:restfieldStudy:MetricFoldMismatch', ...
        'Metric case does not belong to its outer validation fold.');
end
for f=1:3
    entries=completed(completed.Fold==f & ...
        (completed.Stage=="architecture" | completed.Stage=="optimizer" | completed.Stage=="gpr"),:);
    assert(all(entries.TrainingCases==256 & entries.ValidationCases==128), ...
        'femstudy:restfieldStudy:TrainingCountMismatch', ...
        'CV run count differs from the preregistered 256/128 split.');
end

architecture=load(fullfile(out,'architecture_selection.mat'),'value');
optimizer=load(fullfile(out,'optimizer_selection.mat'),'value');
assert(strcmp(architecture.value.provenance.configSHA256,prepared.provenance.configSHA256) && ...
    strcmp(optimizer.value.provenance.configSHA256,prepared.provenance.configSHA256), ...
    'femstudy:restfieldStudy:SelectionHashMismatch','Selection artifacts have inconsistent provenance.');
chosen=architecture.value.chosenArchitectureID;
adam=completed(completed.Stage=="architecture" & ...
    contains(completed.BaseRunID,"A_"+chosen+"_"),:);
lbfgs=completed(completed.Stage=="optimizer" & ...
    contains(completed.BaseRunID,"B_LBFGS_"+chosen+"_"),:);
assert(height(adam)==9 && height(lbfgs)==9, ...
    'femstudy:restfieldStudy:OptimizerPairsMissing', ...
    'Selected architecture does not have all nine paired optimizer runs.');
for i=1:height(adam)
    a=load(adam.Artifact(i),'value');
    match=find(lbfgs.Fold==adam.Fold(i) & lbfgs.Seed==adam.Seed(i),1);
    assert(~isempty(match),'femstudy:restfieldStudy:OptimizerPairMissing','Missing paired optimizer run.');
    b=load(lbfgs.Artifact(match),'value');
    assert(strcmp(a.value.model.initialWeightsHash,b.value.model.initialWeightsHash), ...
        'femstudy:restfieldStudy:InitialWeightMismatch','Optimizer initial weights differ.');
end
final=completed(completed.Stage=="final_fit",:);
assert(height(final)==3 && all(final.TrainingCases==384 & final.ValidationCases==0) && ...
    numel(unique(final.Seed))==3, ...
    'femstudy:restfieldStudy:FinalFitGridInvalid', ...
    'Final selected configuration is not fitted on all 384 cases for each seed.');
for i=1:height(final)
    model=load(final.Artifact(i),'value');
    assert(isequal(sort(model.value.model.trainIDs),sort(folds.ID)) && ...
        model.value.model.pod.r<=cfg.pod.maximumRank, ...
        'femstudy:restfieldStudy:FinalFitLeakage','Final model training IDs or POD rank invalid.');
end
fprintf(['Audit passed: 384 cases, 3 folds x 256/128, %d CV metric rows, ' ...
    'selected architecture %s, optimizer %s, 3 final 384-case fits.\n'], ...
    height(metrics),architecture.value.chosenArchitecture,optimizer.value.chosenOptimizer);
fprintf('Attempt statuses: completed=%d, failed=%d, aborted=%d.\n', ...
    nnz(ledger.Status=="completed"),nnz(ledger.Status=="failed"),nnz(ledger.Status=="aborted"));
finalFitSummary=readtable(fullfile(out,'final_fit_seed_training.csv'),'TextType','string');
assert(height(finalFitSummary)==3 && ...
    isequal(sort(finalFitSummary.Seed),[42;43;44]) && ...
    all(finalFitSummary.TrainingCases==384) && ...
    all(finalFitSummary.TrainingSeconds>0) && ...
    all(finalFitSummary.PODRank<=cfg.pod.maximumRank), ...
    'femstudy:restfieldStudy:FinalFitSummaryInvalid', ...
    'Final fit time/seed summary does not match the three frozen 384-case models.');
assert(isfile(fullfile(out,'FINAL_REPORT_v2.md')) && ...
    isfile(fullfile(out,'attempt_ledger_final.csv')), ...
    'femstudy:restfieldStudy:FinalEvidenceMissing', ...
    'Final report or frozen attempt ledger is missing.');
end

function hash=combinedCodeHash(provenance)
digest=java.security.MessageDigest.getInstance('SHA-256');
bytes=uint8(char(join(provenance.codeSHA256,"")));
digest.update(typecast(bytes,'int8'));
hash=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

function ledger=readAttemptLedger(path)
options=detectImportOptions(path,'TextType','string');
textVariables={'RunID','BaseRunID','Stage','Model','Architecture','Optimizer', ...
    'StartedAt','StopReason','Status','ErrorIdentifier','ErrorMessage','Artifact', ...
    'ConfigSHA256','DataSHA256','CodeSHA256'};
options=setvartype(options,textVariables,'string');
ledger=readtable(path,options);
end

function hash=sha256File(path)
fid=fopen(path,'rb');
assert(fid>=0,'femstudy:restfieldStudy:HashRead','Cannot open file for hashing: %s',path);
cleanup=onCleanup(@()fclose(fid));
bytes=fread(fid,Inf,'*uint8');
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
hash=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
clear cleanup
end
