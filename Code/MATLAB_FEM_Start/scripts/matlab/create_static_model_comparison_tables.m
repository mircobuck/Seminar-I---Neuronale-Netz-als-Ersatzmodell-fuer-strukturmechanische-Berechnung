function create_static_model_comparison_tables()
%CREATE_STATIC_MODEL_COMPARISON_TABLES Summarize existing static study results.
% The comparison intentionally retains test-cohort provenance. It does not
% claim that results from different held-out case sets are directly comparable.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
active=fullfile(root,'experiments','active');
out=fullfile(active,'static_model_comparison_20261028_v1');
assert(~isfolder(out),'femstudy:comparison:OutputExists', ...
    'Comparison output already exists; preserve the existing synthesis.');

trainRoot=fullfile(active,'training_size_12_24_48_20261023');
romRoot=fullfile(active,'pod_galerkin_20261023_v1');
neuralRoot=fullfile(active,'neural_comparison_20261027_v1');
deepRoot=fullfile(root,'experiments','archive','deeponet_20261023_v1');
confirmRoot=fullfile(active,'static_confirmation_v1');
required={fullfile(trainRoot,'comparison.csv'), ...
    fullfile(romRoot,'comparison.csv'),fullfile(deepRoot,'deeponet_summary.csv'), ...
    fullfile(neuralRoot,'static_test_summary.csv'), ...
    fullfile(confirmRoot,'summary.csv'),fullfile(confirmRoot,'case_metrics.csv')};
required{end+1}=fullfile(deepRoot,'baseline_summary.csv');
assert(all(cellfun(@isfile,required)),'femstudy:comparison:MissingSource', ...
    'One or more required prior-study result files are missing.');

historical=readtable(required{1}); rom=readtable(required{2});
deep=readtable(required{3}); neural=readtable(required{4});
confirmation=readtable(required{5}); caseMetrics=readtable(required{6});
deepBaseline=readtable(required{7});
historical.Model=string(historical.Model); rom.Model=string(rom.Model);
neural.Model=string(neural.Model); deepBaseline.Model=string(deepBaseline.Model);
deepTestCases=6; confirmationTestCases=64; neuralTestCases=64;
field=struct('Model',{},'TrainingCases',{},'MedianFieldErrorPct',{}, ...
    'P95FieldErrorPct',{},'MaxFieldErrorPct',{},'SeedCount',{}, ...
    'SeedMedianMinPct',{},'SeedMedianMaxPct',{},'TestCases',{}, ...
    'TestCohort',{},'Source',{},'Notes',{});

% Shared historical six-case cohort: classic POD regressors and POD-Galerkin.
for i=1:height(rom)
    if ~ismember(rom.Model(i),["POD_Galerkin","POD_GP","POD_RBF","POD_MLP"])
        continue
    end
    source="pod_galerkin_20261023_v1/comparison.csv";
    note="Known test IDs 19-24; one fixed legacy model realization.";
    field(end+1)=fieldRow(rom.Model(i),rom.TrainingCases(i), ...
        100*rom.FieldMedianRelL2(i),100*rom.FieldP95RelL2(i), ...
        100*rom.FieldWorstRelL2(i),1,100*rom.FieldMedianRelL2(i), ...
        100*rom.FieldMedianRelL2(i),deepTestCases, ...
        "historical shared IDs 19-24",source,note); %#ok<AGROW>
end

% DeepONet historical results: five model seeds on the same six known cases.
for n=unique(deep.TrainingCases(:))'
    rows=deep.TrainingCases==n;
    med=100*deep.FieldMedianRelL2(rows);
    field(end+1)=fieldRow("DeepONet",n,median(med), ...
        100*median(deep.FieldP95RelL2(rows)), ...
        100*median(deep.FieldWorstRelL2(rows)),nnz(rows), ...
        min(med),max(med),deepTestCases,"historical shared IDs 19-24", ...
        "archive/deeponet_20261023_v1/deeponet_summary.csv", ...
        "Median of five seed-level metrics; seed span shown."); %#ok<AGROW>
end

% New 64-case static test cohort: new neural models and frozen reference models.
for model=["Neural_pod","Neural_residual"]
    for n=unique(neural.N(neural.Model==model))'
        rows=neural.Model==model & neural.N==n;
        med=100*neural.MedianRelativeError(rows);
        field(end+1)=fieldRow(model,n,median(med), ...
            100*median(neural.P95RelativeError(rows)), ...
            100*median(neural.MaxRelativeError(rows)),nnz(rows), ...
            min(med),max(med),neuralTestCases, ...
            "neural comparison: 64 final cases", ...
            "neural_comparison_20261027_v1/static_test_summary.csv", ...
            "Median across three seed-level summaries; seed span shown."); %#ok<AGROW>
    end
end
for model=["Legacy_POD_GP","Legacy_POD_RBF","Legacy_POD_MLP","DeepONet"]
    rows=neural.Model==model;
    for n=unique(neural.N(rows))'
        r=rows & neural.N==n;
        med=100*neural.MedianRelativeError(r);
        field(end+1)=fieldRow(model,n,median(med), ...
            100*median(neural.P95RelativeError(r)), ...
            100*median(neural.MaxRelativeError(r)),nnz(r), ...
            min(med),max(med),neuralTestCases, ...
            "neural comparison: 64 final cases", ...
            "neural_comparison_20261027_v1/static_test_summary.csv", ...
            "Frozen historical model evaluated on the new 64-case test set."); %#ok<AGROW>
    end
end
beam=neural.Model=="Beam_theory_field";
field(end+1)=fieldRow("Beam_theory_field",0, ...
    100*neural.MedianRelativeError(beam), ...
    100*neural.P95RelativeError(beam),100*neural.MaxRelativeError(beam), ...
    0,NaN,NaN,neuralTestCases, ...
    "neural comparison: 64 final cases", ...
    "neural_comparison_20261027_v1/static_test_summary.csv", ...
    "Analytical displacement-field baseline; no training.");

% Separate, independent confirmation cohort: model 3 is the normalized hybrid.
caseModel=caseMetrics.model==3;
assert(any(caseModel),'femstudy:comparison:HybridCases', ...
    'Hybrid case-level metrics are missing.');
hybridErrors=caseMetrics.fieldPct(caseModel);
hybridSummary=confirmation.model==3;
assert(nnz(hybridSummary)==1,'femstudy:comparison:HybridSummary', ...
    'Expected one stored aggregate for hybrid model 3.');
field(end+1)=fieldRow("Beam_Field_POD_GPR (normalized hybrid)",18, ...
    median(hybridErrors),confirmation.p95Pct(hybridSummary),max(hybridErrors), ...
    1,median(hybridErrors),median(hybridErrors),confirmationTestCases, ...
    "static confirmation: 64 cases", ...
    "static_confirmation_v1/case_metrics.csv", ...
    "Model 3; frozen normalized hybrid; 18 training cases from protocol.");
beamCase=caseMetrics.model==1;
assert(any(beamCase),'femstudy:comparison:BeamCases', ...
    'Beam-field confirmation rows are missing.');
beamErrors=caseMetrics.fieldPct(beamCase);
beamSummary=confirmation.model==1;
field(end+1)=fieldRow("Beam_theory_field",0,median(beamErrors), ...
    confirmation.p95Pct(beamSummary),max(beamErrors),0,NaN,NaN, ...
    confirmationTestCases,"static confirmation: 64 cases", ...
    "static_confirmation_v1/case_metrics.csv", ...
    "Analytical beam field; median and maximum derived from its 64 case rows.");

fieldTable=struct2table(field);
fieldTable=sortrows(fieldTable,{'Model','TrainingCases','TestCohort'});

% Scalar targets are compared only by tip-displacement MAE (micrometres).
scalar=historical(ismember(historical.Model, ...
    ["Scalar_GPR","Beam_plus_GPR"]),:);
scalarRows=struct('Model',{},'TrainingCases',{},'TipMAE_um',{}, ...
    'TestCases',{},'TestCohort',{},'Source',{},'Notes',{});
for i=1:height(scalar)
    scalarRows(end+1)=struct('Model',scalar.Model(i), ...
        'TrainingCases',scalar.TrainingCases(i), ...
        'TipMAE_um',1e6*scalar.TipMAE_m(i),'TestCases',deepTestCases, ...
        'TestCohort',"historical shared IDs 19-24", ...
        'Source',"training_size_12_24_48_20261023/comparison.csv", ...
        'Notes',"Tip displacement MAE; not a field-error metric."); %#ok<AGROW>
end
beamHistorical=deepBaseline.Model=="Beam_theory" & ...
    deepBaseline.TrainingCases==12;
assert(nnz(beamHistorical)==1,'femstudy:comparison:HistoricalBeam', ...
    'Expected one historical analytical beam scalar baseline.');
beamHistoricalRow=deepBaseline(beamHistorical,:);
scalarRows(end+1)=struct('Model',"Beam_theory",'TrainingCases',0, ...
    'TipMAE_um',1e6*beamHistoricalRow.TipMAE_m,'TestCases',deepTestCases, ...
    'TestCohort',"historical shared IDs 19-24", ...
    'Source',"archive/deeponet_20261023_v1/baseline_summary.csv", ...
    'Notes',"Analytical beam-tip baseline; no training.");
rows=caseMetrics.model==1;
scalarRows(end+1)=struct('Model',"Beam_theory",'TrainingCases',0, ...
    'TipMAE_um',1e6*mean(caseMetrics.tipAbsM(rows)), ...
    'TestCases',confirmationTestCases, ...
    'TestCohort',"static confirmation: 64 cases", ...
    'Source',"static_confirmation_v1/case_metrics.csv", ...
    'Notes',"Analytical beam-tip baseline; mean absolute tip error.");
scalarTable=struct2table(scalarRows);
scalarTable=sortrows(scalarTable,{'Model','TrainingCases'});

mkdir(out);
writetable(fieldTable,fullfile(out,'static_field_comparison.csv'));
writetable(scalarTable,fullfile(out,'static_scalar_comparison.csv'));
writeMarkdown(out,fieldTable,scalarTable);
fprintf('Field comparison rows: %d\nScalar comparison rows: %d\nOutput: %s\n', ...
    height(fieldTable),height(scalarTable),out);
end

function row=fieldRow(model,n,medianPct,p95Pct,maxPct,seedCount, ...
    seedMin,seedMax,testCases,cohort,source,notes)
row=struct('Model',string(model),'TrainingCases',n, ...
    'MedianFieldErrorPct',medianPct,'P95FieldErrorPct',p95Pct, ...
    'MaxFieldErrorPct',maxPct,'SeedCount',seedCount, ...
    'SeedMedianMinPct',seedMin,'SeedMedianMaxPct',seedMax, ...
    'TestCases',testCases,'TestCohort',string(cohort), ...
    'Source',string(source),'Notes',string(notes));
end

function writeMarkdown(out,field,scalar)
path=fullfile(out,'COMPARISON_TABLES.md');
fid=fopen(path,'wt');
assert(fid>=0,'femstudy:comparison:WriteMarkdown', ...
    'Could not open markdown comparison output for writing.');
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'# Statische Modellvergleiche\n\n');
fprintf(fid,'Abgeleitet aus bereits gespeicherten Studien; es wurden keine FEM-Faelle ');
fprintf(fid,'neu berechnet und keine Modelle neu trainiert.\n\n');
fprintf(fid,'## 1. Statische Verschiebungsfelder\n\n');
fprintf(fid,['Fehlerwerte der gewichteten relativen Feld-L2-Norm in Prozent. ' ...
    'Bei mehreren Seeds sind Median, P95 und Maximum jeweils der Median ' ...
    'der seedweisen Kennzahlen; die Seed-Spanne zeigt Minimum bis Maximum ' ...
    'der seedweisen Medianfehler. `NaN` bedeutet nicht verfuegbar/nicht berichtet.\n\n']);
fprintf(fid,['| Modell | n | Medianfeldfehler | P95 | Maximum | Seeds | ' ...
    'Seed-Spanne | Testfaelle/Kohorte |\n|---|---:|---:|---:|---:|---:|---:|---|\n']);
for i=1:height(field)
    span="-";
    if field.SeedCount(i)>1
        span=sprintf('%.4g-%.4g%%',field.SeedMedianMinPct(i), ...
            field.SeedMedianMaxPct(i));
    end
    fprintf(fid,'| %s | %g | %s | %s | %s | %d | %s | %d / %s |\n', ...
        field.Model(i),field.TrainingCases(i),fmt(field.MedianFieldErrorPct(i)), ...
        fmt(field.P95FieldErrorPct(i)),fmt(field.MaxFieldErrorPct(i)), ...
        field.SeedCount(i),span,field.TestCases(i),field.TestCohort(i));
end
fprintf(fid,'\n');
fprintf(fid,'## 2. Statische Kennwerte\n\n');
fprintf(fid,'Spitzenverschiebungs-MAE in Mikrometern; diese Werte sind ');
fprintf(fid,['keine Feldfehler und separat zu lesen. `Beam_plus_GPR` bezeichnet ' ...
    'die Balkentheorie mit skalarer GPR-Korrektur.\n\n']);
fprintf(fid,'| Modell | n | Spitze-MAE (um) | Testfaelle/Kohorte |\n|---|---:|---:|---|\n');
for i=1:height(scalar)
    fprintf(fid,'| %s | %g | %.6g | %d / %s |\n', ...
        scalar.Model(i),scalar.TrainingCases(i),scalar.TipMAE_um(i), ...
        scalar.TestCases(i),scalar.TestCohort(i));
end
fprintf(fid,'\n## Vergleichbarkeit und Herkunft\n\n');
fprintf(fid,['Die Tabellen bewahren die Testkohorte jeder Zahl. Die bekannten ' ...
    'Testfaelle 19-24, die 64 neuralen Finalfaelle und die 64 Faelle der ' ...
    'statischen Bestaetigungsstudie sind unterschiedliche Kohorten. Werte ' ...
    'aus verschiedenen Kohorten sind daher keine gepaarte Rangliste. Die ' ...
    'neuen 64-Fall-Modelle und ihre eingefrorenen Referenzen teilen dagegen ' ...
    'dieselbe Testkohorte. Das Beam_Field_POD_GPR-Ergebnis ist die naechstliegende ' ...
    'eingefrorene normalisierte Hybridvariante, nicht die Behauptung identischer ' ...
    'Artefakte.\n\n']);
fprintf(fid,'CSV-Spalten `Source` und `Notes` enthalten die jeweiligen Quelldateien und Details.\n');
clear cleanup
end

function text=fmt(value)
if isnan(value)
    text="-";
else
    text=sprintf('%.4g%%',value);
end
end
