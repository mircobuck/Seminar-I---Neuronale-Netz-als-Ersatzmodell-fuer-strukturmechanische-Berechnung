function [hashes,fingerprint]=hashManifest(root,paths)
hashes=strings(numel(paths),1);
manifest=strings(numel(paths),1);
for i=1:numel(paths)
    hashes(i)=sha256(paths(i));
    relative=erase(paths(i),string(root)+filesep);
    manifest(i)=replace(relative,"\","/")+" "+hashes(i);
end
fingerprint=sha256Text(join(manifest,newline));
end

function value=sha256(path)
fid=fopen(path,'rb');
assert(fid>=0,'femstudy:audit:HashRead','Cannot read file for hashing: %s',path);
cleaner=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes=fread(fid,1024*1024,'*uint8');
    if isempty(bytes), break; end
    md.update(typecast(bytes(:),'int8'));
end
digest=typecast(md.digest(),'uint8');
value=lower(string(reshape(dec2hex(digest,2).',1,[])));
clear cleaner
end

function value=sha256Text(text)
md=java.security.MessageDigest.getInstance('SHA-256');
bytes=unicode2native(char(text),'UTF-8');
md.update(typecast(uint8(bytes(:)),'int8'));
digest=typecast(md.digest(),'uint8');
value=lower(string(reshape(dec2hex(digest,2).',1,[])));
end

