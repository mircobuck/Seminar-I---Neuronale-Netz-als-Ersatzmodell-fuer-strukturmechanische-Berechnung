end

function verifyAggregates(summary,perCase,keyVars,label)
for i=1:height(summary)
    q=keys(perCase,keyVars)==keys(summary(i,:),keyVars);
    e=perCase.RelativeFieldError(q);
    e=e(isfinite(e)); s=sort(e);
    assert(~isempty(s) && closeEnough(summary.MedianRelativeError(i),median(s)) && ...
        closeEnough(summary.P95RelativeError(i),s(ceil(.95*numel(s)))) && ...
        closeEnough(summary.MaxRelativeError(i),max(s)) && ...
        closeEnough(summary.MeanRelativeError(i),mean(e)), ...
        'femstudy:audit:AggregateMismatch', ...
        '%s aggregated field metrics do not reproduce for key %s.',label, ...
        keys(summary(i,:),keyVars));
end
end

function verifyModalAggregates(summary,perCase)
for i=1:height(summary)
    q=keys(perCase,{'Model','N','Seed'})== ...
        keys(summary(i,:),{'Model','N','Seed'});
    raw=perCase.MeanRelativeRaw(q); sorted=perCase.MeanRelativeSorted(q);
    viol=perCase.OrderViolation(q);
    assert(~isempty(raw) && closeEnough(summary.MedianRelativeRaw(i),median(raw)) && ...
        closeEnough(summary.MedianRelativeSorted(i),median(sorted)) && ...
        closeEnough(summary.MaxRelativeRaw(i),max(raw)) && ...
        closeEnough(summary.MaxRelativeSorted(i),max(sorted)) && ...
        closeEnough(summary.OrderViolationFraction(i),mean(viol)), ...
        'femstudy:audit:ModalAggregateMismatch', ...
        'Modal aggregated metrics do not reproduce for key %s.', ...
        keys(summary(i,:),{'Model','N','Seed'}));
end
end

function assertGroupCoverage(t,groupVars,expected,expectedCount,label)
groups=unique(keys(t,groupVars));
for i=1:numel(groups)
    same=keys(t,groupVars)==groups(i);
    if ismember('TestID',t.Properties.VariableNames)
        actual=t.TestID(same);
    else
        actual=t.Mode(same);
    end
    assert(numel(actual)==expectedCount && ...
        isequal(sort(actual(:)),sort(expected(:))), ...
        'femstudy:audit:GroupCoverage', ...
        '%s cases/indices incomplete or duplicated for key %s.', ...
        label,groups(i));
end
end

function checkStaticReferences(study,design)
for i=1:numel(design.id)
    path=fullfile(study,'static_cases', ...
        sprintf('case_%06d.mat',design.id(i)));
    requireFiles({path});
    a=load(path);
    assert(isfield(a,'value'),'femstudy:audit:StaticCaseSchema', ...
        'Missing static case value: %s',path);
    v=a.value;
    assert(isfield(v,'status') && v.status=="success" && ...
        isequal(v.x,design.X(i,:)) && isequal(size(v.S),[1575 1]) && ...
        isequal(size(v.xi),[3 525]) && numel(v.w)==1575 && ...
        isequal(size(v.Y),[1 2]) && all(isfinite(v.S)) && ...
        all(isfinite(v.Y)), ...
        'femstudy:audit:StaticCaseData', ...
        'Static test reference parameters, dimensions, or values invalid: %s',path);
end
end

function checkModalReferences(study,design)
for i=1:numel(design.id)
    if design.split(i)=="test"
        folder='modal_test_cases';
    else
        folder='modal_cases';
    end
    path=fullfile(study,folder,sprintf('case_%06d.mat',design.id(i)));
    requireFiles({path});
    a=load(path);
    assert(isfield(a,'value'),'femstudy:audit:ModalCaseSchema', ...
        'Missing modal case value: %s',path);
    v=a.value;
    assert(isequal(v.parameters,design.X(i,:)) && ...
        numel(v.frequencyHz)>=8 && all(isfinite(v.frequencyHz)) && ...
        all(v.frequencyHz>0) && isequal(size(v.queryCoordinates),[3 525]) && ...
        size(v.queryModes,1)==1575 && ...
        size(v.queryModes,2)>=8, ...
        'femstudy:audit:ModalCaseData', ...
        'Modal reference parameters, dimensions, or values invalid: %s',path);
end
end

function assertRepeatCoverage(t,groupVars,testIDs,repeats,label)
for g=unique(keys(t,groupVars))'
    group=keys(t,groupVars)==g;
    for id=testIDs(:)'
        q=group & t.TestID==id;
        assert(nnz(q)==repeats && isequal(sort(t.Repeat(q)),(1:repeats)'), ...
            'femstudy:audit:RepeatCoverage', ...
            '%s repeat IDs are incomplete for %s / test ID %g.',label,g,id);
    end
end
end

function yes=closeEnough(a,b)
yes=abs(a-b)<=1e-12*max(1,max(abs(a),abs(b)));
end

function yes=arrayClose(a,b)
