function audit_neural_comparison_integrity()
%AUDIT_NEURAL_COMPARISON_INTEGRITY Read-only audit of the completed v1 study.
% No FEM solves, model fitting, prediction, result rewriting, or test selection.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
study=fullfile(root,'experiments','active','neural_comparison_20261027_v1');
cfgPath=fullfile(root,'configs','neural_comparison_v1.json');
configPath=fullfile(root,'config.m');
protocolPath=fullfile(study,'PROTOCOL.md');
progressPath=fullfile(study,'PROGRESS_20261027.md');
matFiles={fullfile(study,'prepared.mat'), ...
    fullfile(study,'static_test_evaluation.mat'), ...
    fullfile(study,'modal_test_evaluation.mat')};
staticCsv={fullfile(study,'static_test_summary.csv'), ...
    fullfile(study,'static_test_per_case.csv'), ...
    fullfile(study,'static_test_timing.csv')};
modalCsv={fullfile(study,'modal_test_summary.csv'), ...
    fullfile(study,'modal_test_per_case.csv'), ...
    fullfile(study,'modal_test_per_mode.csv'), ...
    fullfile(study,'modal_test_timing.csv')};
findings=strings(0,1);
deviations=strings(0,1);
hashPaths=strings(0,1);
hashValues=strings(0,1);
revision="unavailable";

try
    requireFiles([{cfgPath,configPath,protocolPath,progressPath},matFiles, ...
        staticCsv,modalCsv]);
    cfg=jsondecode(fileread(cfgPath));
    prepared=load(matFiles{1});
    staticEval=load(matFiles{2});
    modalEval=load(matFiles{3});
    assert(isfield(prepared,'value') && isfield(staticEval,'value') && ...
        isfield(modalEval,'value'), ...
        'femstudy:audit:MatSchema','Expected saved MAT variable `value`.');
    p=prepared.value; se=staticEval.value; me=modalEval.value;

    expectedSizes=[12 24 48 96 192 384];
    expectedSeeds=[42 43 44];
    assert(isequal(cfg.sizes(:)',expectedSizes) && ...
        isequal(cfg.seeds(:)',expectedSeeds) && cfg.finalCount==64 && ...
        cfg.modalValidationCount==12 && cfg.modalTestCount==64, ...
        'femstudy:audit:Config','Unexpected study sizes, seeds, or final counts.');
    assert(isequaln(p.config,cfg),'femstudy:audit:ConfigMismatch', ...
        'prepared.mat configuration differs from the checked-in study config.');
    findings(end+1)="Studienkonfiguration und Konfiguration in prepared.mat stimmen ueberein.";

    c=config('smoke');
    staticNames={'L_m','b_m','h_m','E_Pa','nu','Fz_N'};
    modalNames={'L_m','b_m','h_m','E_Pa','nu','rho_kg_m3'};
    assert(isequal(cellstr(c.names(:))',staticNames), ...
        'femstudy:audit:StaticParameterOrder', ...
        'Static parameter order differs from [L_m,b_m,h_m,E_Pa,nu,Fz_N].');
    staticDesign=readtable(fullfile(study,'static_final_design.csv'));
    modalDesign=readtable(fullfile(study,'modal_design.csv'));
    assert(isequal(staticDesign.Properties.VariableNames, ...
        [{'id'},staticNames]),'femstudy:audit:StaticDesignColumns', ...
        'Static design columns or parameter order are incorrect.');
    assert(isequal(modalDesign.Properties.VariableNames, ...
        [{'id'},modalNames,{'split'}]),'femstudy:audit:ModalDesignColumns', ...
        'Modal design columns or parameter order are incorrect.');
    assert(isequal(size(p.staticFinal.X),[cfg.finalCount 6]) && ...
        isequal(p.staticFinal.id(:),staticDesign.id) && ...
        arrayClose(p.staticFinal.X,staticDesign{:,staticNames}), ...
        'femstudy:audit:StaticDesignMismatch', ...
        'Static design CSV does not match the sealed prepared MAT design.');
    assert(isequal(p.modal.id(:),modalDesign.id) && ...
        arrayClose(p.modal.X,modalDesign{:,modalNames}) && ...
        isequal(p.modal.split(:),string(modalDesign.split)), ...
        'femstudy:audit:ModalDesignMismatch', ...
        'Modal design CSV does not match the sealed prepared MAT design.');
    assert(numel(unique(p.staticFinal.id))==numel(p.staticFinal.id) && ...
        numel(unique(p.modal.id))==numel(p.modal.id), ...
        'femstudy:audit:DuplicateDesignIDs','Duplicate final/design IDs found.');
    assert(nnz(p.modal.split=="train")==384 && ...
        nnz(p.modal.split=="val")==cfg.modalValidationCount && ...
        nnz(p.modal.split=="test")==cfg.modalTestCount, ...
        'femstudy:audit:ModalSplitCounts', ...
        'Modal design split counts do not match the preregistered counts.');
    findings(end+1)="Statische und modale Parameternamen/-reihenfolge, Design-CSV-Dateien und Split-Anzahlen stimmen.";

    staticTestIDs=p.staticFinal.id(:);
    modalTrainIDs=p.modal.id(p.modal.split=="train");
    modalValIDs=p.modal.id(p.modal.split=="val");
    modalTestIDs=p.modal.id(p.modal.split=="test");
    assert(isempty(intersect(staticTestIDs,[p.modal.id(:)])), ...
        'femstudy:audit:CrossStudyIDOverlap', ...
        'Static final IDs overlap modal design IDs unexpectedly.');
    assert(isempty(intersect(modalTrainIDs,modalValIDs)) && ...
        isempty(intersect(modalTrainIDs,modalTestIDs)) && ...
        isempty(intersect(modalValIDs,modalTestIDs)), ...
        'femstudy:audit:ModalIDOverlap','Modal split IDs overlap.');
    assert(isequal(se.testIDs(:),staticTestIDs) && ...
        isequal(me.testIDs(:),modalTestIDs), ...
        'femstudy:audit:EvaluationTestIDs', ...
        'Stored evaluation test IDs do not match sealed final designs.');
    findings(end+1)=sprintf('Finale Designs sind disjunkt und stimmen mit den Auswertungs-MAT-IDs ueberein: %d statische, %d modale Testfaelle.', ...
        numel(staticTestIDs),numel(modalTestIDs));
    checkStaticReferences(study,p.staticFinal);
    checkModalReferences(study,p.modal);
    findings(end+1)=sprintf(['Parametervektoren und Ausgabedimensionen in %d statischen ' ...
        'und %d modalen FEM-Referenz-MAT-Dateien geprueft.'], ...
        numel(staticTestIDs),numel(p.modal.id));

    staticSource=fullfile(root,cfg.source);
    staticValIDs=cell(numel(expectedSizes),1);
    staticTrainIDs=cell(numel(expectedSizes),1);
    for ni=1:numel(expectedSizes)
        n=expectedSizes(ni);
        trainFile=fullfile(staticSource,"n"+n,'train.mat');
        valFile=fullfile(staticSource,"n"+n,'val.mat');
        requireFiles({trainFile,valFile});
        trainData=load(trainFile); valData=load(valFile);
        assert(isfield(trainData,'D') && isfield(valData,'D'), ...
            'femstudy:audit:StaticSourceSchema', ...
            'Expected D in static training/validation files for n=%d.',n);
        trainIDs=trainData.D.id(:); valIDs=valData.D.id(:);
        assert(size(trainData.D.X,2)==6 && size(valData.D.X,2)==6 && ...
            size(trainData.D.S,1)==1575 && size(valData.D.S,1)==1575, ...
            'femstudy:audit:StaticSourceDimensions', ...
            'Static source parameter/field dimensions mismatch at n=%d.',n);
        assert(numel(trainIDs)==n && numel(unique(trainIDs))==n && ...
            numel(unique(valIDs))==numel(valIDs) && ...
            isempty(intersect(trainIDs,valIDs)) && ...
            isempty(intersect([trainIDs;valIDs],staticTestIDs)), ...
            'femstudy:audit:StaticSourceIDs', ...
            'Static source IDs overlap, duplicate, or have wrong count at n=%d.',n);
        assert(numel(valIDs)==6,'femstudy:audit:StaticValidationCount', ...
            'Expected six static validation IDs at n=%d.',n);
        staticTrainIDs{ni}=trainIDs; staticValIDs{ni}=valIDs;
    end
    for ni=2:numel(expectedSizes)
        assert(isequal(staticTrainIDs{ni}, ...
            staticTrainIDs{end}(1:expectedSizes(ni))) && ...
            isequal(staticValIDs{ni},staticValIDs{1}), ...
            'femstudy:audit:StaticNestedIDs', ...
            'Static training IDs are not nested or validation IDs changed at n=%d.', ...
            expectedSizes(ni));
    end

    staticModelCount=0;
    for ni=1:numel(expectedSizes)
        n=expectedSizes(ni);
        for seed=expectedSeeds
            for kind=["pod","residual"]
                modelPath=fullfile(study,"n"+n,"seed"+seed,kind+'.mat');
                requireFiles({modelPath});
                artifact=load(modelPath);
                assert(isfield(artifact,'value'),'femstudy:audit:StaticModelSchema', ...
                    'Missing value in static model: %s',modelPath);
                m=artifact.value;
                assert(isequal(m.trainIDs(:),staticTrainIDs{ni}) && ...
                    isequal(m.validationIDs(:),staticValIDs{ni}) && ...
                    m.seed==seed && m.kind==kind, ...
                    'femstudy:audit:StaticModelIDs', ...
                    'Static model IDs, kind, or seed mismatch: %s',modelPath);
                assert(isfield(m,'pod') && isequal(size(m.pod.mean),[1575 1]) && ...
                    isequal(size(m.xi),[3 525]) && ...
                    numel(m.pod.V(:,1))==1575, ...
                    'femstudy:audit:StaticModelDimensions', ...
                    'Static field model dimensions/order mismatch: %s',modelPath);
                staticModelCount=staticModelCount+1;
            end
        end
        gpPath=fullfile(study,"n"+n,'frequency_gp.mat');
        requireFiles({gpPath});
        gp=load(gpPath); m=gp.value;
        assert(isequal(m.trainIDs(:),modalTrainIDs(1:n)) && ...
            isequal(m.validationIDs(:),modalValIDs) && m.seed==42 && ...
            numel(m.net)==6,'femstudy:audit:FrequencyGPRIDs', ...
            'Frequency GPR model IDs, seed, or six-output shape mismatch: %s',gpPath);
        assert(isequal(size(m.xm),[1 6]) && isequal(size(m.ym),[1 6]), ...
            'femstudy:audit:FrequencyGPRDimensions', ...
            'Frequency GPR input/output parameter dimensions mismatch: %s',gpPath);
        for seed=expectedSeeds
            modelPath=fullfile(study,"n"+n,"seed"+seed,'frequency_mlp.mat');
            requireFiles({modelPath});
            artifact=load(modelPath); m=artifact.value;
            assert(isequal(m.trainIDs(:),modalTrainIDs(1:n)) && ...
                isequal(m.validationIDs(:),modalValIDs) && ...
                m.seed==seed && m.kind=="frequency", ...
                'femstudy:audit:FrequencyMLPIDs', ...
                'Frequency MLP IDs, kind, or seed mismatch: %s',modelPath);
        end
    end
    findings(end+1)=sprintf(['IDs und Seeds fuer %d statische Feldmodell-Artefakte, ' ...
        '%d Frequenz-GPRs und %d Frequenz-MLPs bei allen sechs Trainingsgroessen geprueft.'], ...
        staticModelCount,numel(expectedSizes),numel(expectedSizes)*numel(expectedSeeds));

    assert(contains(fileread(protocolPath),'ux,uy,uz') && ...
        contains(fileread(protocolPath),'Hz') && ...
        contains(fileread(protocolPath),'m'), ...
        'femstudy:audit:DocumentationContract', ...
        'Protocol does not document required field order and SI units.');
    assert(isequal(size(se.perCase.RelativeFieldError), ...
        [numel(staticTestIDs)*45 1]) && ...
        isequal(size(me.perMode.Mode),[24*6 1]), ...
        'femstudy:audit:EvaluationDimensions', ...
        'Evaluation MAT dimensions do not match expected field/frequency output sizes.');
    findings(end+1)=['Dokumentierte Feldkomponentenfolge ux,uy,uz; statische Felder haben ' ...
        '3x525=1575 Werte in Metern, modale Ziele sind sechs positive Frequenzen in Hz.'];

    assert(isequal(string(se.schema),"static-neural-final-evaluation-v1") && ...
        isequal(string(me.schema),"modal-frequency-final-evaluation-v1"), ...
        'femstudy:audit:EvaluationSchema','Unexpected final evaluation schema.');
    compareTable(se.summary,staticCsv{1}, ...
        {'Model','N','Seed'},'static summary');
    compareTable(se.perCase,staticCsv{2}, ...
        {'Model','N','Seed','TestID'},'static per-case');
    compareTable(se.timing,staticCsv{3}, ...
        {'Model','N','Seed','TestID','Repeat'},'static timing');
    compareTable(me.summary,modalCsv{1}, ...
        {'Model','N','Seed'},'modal summary');
    compareTable(me.perCase,modalCsv{2}, ...
        {'Model','N','Seed','TestID'},'modal per-case');
    compareTable(me.perMode,modalCsv{3}, ...
        {'Model','N','Seed','Mode'},'modal per-mode');
    compareTable(me.timing,modalCsv{4}, ...
        {'Model','N','Seed','TestID','Repeat'},'modal timing');

    expectedStaticKeys=staticKeys(expectedSizes,expectedSeeds);
    expectedModalKeys=modalKeys(expectedSizes,expectedSeeds);
    assert(isequal(sort(keys(se.summary,{'Model','N','Seed'})), ...
        sort(expectedStaticKeys(:))),'femstudy:audit:StaticModelKeys', ...
        'Static summary model/seed keys do not match the prescribed design.');
    assert(height(se.summary)==45 && height(se.perCase)==45*64 && ...
        height(se.timing)==45*64*7,'femstudy:audit:StaticRowCounts', ...
        'Static summary, case, or timing row counts are incorrect.');
    assert(isequal(sort(keys(me.summary,{'Model','N','Seed'})), ...
        sort(expectedModalKeys(:))),'femstudy:audit:ModalModelKeys', ...
        'Modal summary model/seed keys do not match the prescribed design.');
    assert(height(me.summary)==24 && height(me.perCase)==24*64 && ...
        height(me.perMode)==24*6 && height(me.timing)==24*64*7, ...
        'femstudy:audit:ModalRowCounts', ...
        'Modal summary, case, mode, or timing row counts are incorrect.');
    assert(all(ismember(unique(me.perCase.TestID),modalTestIDs)) && ...
        all(ismember(unique(se.perCase.TestID),staticTestIDs)), ...
        'femstudy:audit:CaseKeys','Per-case tables contain unexpected test IDs.');
    assert(all(isfinite(se.summary.MedianRelativeError)) && ...
        all(isfinite(se.summary.P95RelativeError)) && ...
        all(isfinite(se.summary.MaxRelativeError)) && ...
        all(isfinite(me.summary.MedianRelativeRaw)) && ...
        all(isfinite(me.summary.MedianRelativeSorted)), ...
        'femstudy:audit:NonFiniteMetrics', ...
        'A required final summary metric is non-finite.');
    assert(all(me.perMode.Mode>=1 & me.perMode.Mode<=6) && ...
        numel(unique(me.perMode.Mode))==6, ...
        'femstudy:audit:ModeKeys','Expected six frequency indices, not mode shapes.');
    assertGroupCoverage(se.perCase,{'Model','N','Seed'}, ...
        staticTestIDs,64,'static per-case');
    assertGroupCoverage(me.perCase,{'Model','N','Seed'}, ...
        modalTestIDs,64,'modal per-case');
    assertRepeatCoverage(se.timing,{'Model','N','Seed'}, ...
        staticTestIDs,7,'static timing');
    assertRepeatCoverage(me.timing,{'Model','N','Seed'}, ...
        modalTestIDs,7,'modal timing');
    assertGroupCoverage(me.perMode,{'Model','N','Seed'}, ...
        (1:6)',6,'modal per-mode');
    findings(end+1)=sprintf(['Alle finalen CSV-Dateien stimmen mit den gespeicherten MAT-Tabellen ' ...
        'ueberein (Toleranz 1e-12 relativ oder absolut); geprueft: %d statische Summary-, ' ...
        '%d statische Fall-, %d statische Timing-, %d modale Summary-, %d modale Fall-, ' ...
        '%d modale Moden- und %d modale Timing-Zeilen.'], ...
        height(se.summary),height(se.perCase),height(se.timing), ...
        height(me.summary),height(me.perCase),height(me.perMode),height(me.timing));
    findings(end+1)=['Rohe und sortierte Frequenzfehler bleiben in Summary-, Fall- und Moden-Tabellen ' ...
        'getrennt; ausgewertet werden Frequenzen, nicht Eigenformvorhersagen.'];

    verifyAggregates(se.summary,se.perCase, ...
        {'Model','N','Seed'},'static');
    verifyModalAggregates(me.summary,me.perCase);
    findings(end+1)=['Summary-Median, P95/Maximum/Mittel der Feldfehler sowie rohe/sortierte ' ...
        'Frequenzmediane, Maxima und Ordnungsverletzungsanteile stimmen mit den gespeicherten ' ...
        'Fall-MAT-Tabellen ueberein.'];

    [status,rev]=system(sprintf('git -C "%s" rev-parse HEAD',root));
    assert(status==0,'femstudy:audit:GitRevision', ...
        'Could not obtain the Git revision for this audit.');
    revision=string(strtrim(rev));
    assert(strlength(revision)==40,'femstudy:audit:GitRevision', ...
        'Git returned an invalid commit ID.');
    hashPaths=collectHashPaths(root,study,cfg, ...
        {cfgPath,configPath,protocolPath,progressPath, ...
         fullfile(root,'scripts','matlab','run_neural_comparison.m'), ...
         fullfile(root,'src','+femstudy','+models','fitNeural.m'), ...
         fullfile(root,'src','+femstudy','+models','fitFrequency.m'), ...
         fullfile(root,'src','+femstudy','+models','predictNeural.m'), ...
         fullfile(root,'src','+femstudy','+models','predictFrequency.m'), ...
         fullfile(root,'src','+femstudy','+metrics','field.m'), ...
         fullfile(root,'src','+femstudy','+metrics','frequency.m'), ...
         fullfile(root,'scripts','matlab','audit_neural_comparison_integrity.m'), ...
         matFiles,staticCsv,modalCsv, ...
         {fullfile(study,'static_final_design.csv'), ...
          fullfile(study,'modal_design.csv')}});
    [hashValues,manifestFingerprint]=hashManifest(root,hashPaths);
    findings(end+1)=sprintf('Git-HEAD %s; SHA-256-Manifest fuer %d Dateien (Fingerabdruck %s).', ...
        revision,numel(hashPaths),manifestFingerprint);
catch err
    deviations(end+1)=string(err.identifier)+": "+string(err.message);
end

reportPath=nextReportPath(study);
writeReport(reportPath,root,revision,findings,deviations,hashPaths,hashValues);
fprintf('Integrity audit report: %s\n',reportPath);
fprintf('Confirmed: %d; deviations: %d; historically not verifiable: 1.\n', ...
    numel(findings),numel(deviations));
if ~isempty(deviations)
    error('femstudy:audit:Deviation','Audit deviation: %s',deviations(1));
end
end

function requireFiles(paths)
for i=1:numel(paths)
    assert(isfile(paths{i}),'femstudy:audit:MissingFile', ...
        'Required audit input is missing: %s',paths{i});
end
end

function compareTable(matTable,csvPath,keyVars,label)
assert(isfile(csvPath),'femstudy:audit:MissingCSV', ...
    'Required result CSV is missing: %s',csvPath);
csvTable=readtable(csvPath);
assert(isequal(matTable.Properties.VariableNames,csvTable.Properties.VariableNames), ...
    'femstudy:audit:CSVColumns','%s CSV columns differ from MAT table: %s', ...
    label,csvPath);
assert(height(matTable)==height(csvTable), ...
    'femstudy:audit:CSVRowCount','%s row count differs between MAT and CSV.',label);
matKeys=keys(matTable,keyVars); csvKeys=keys(csvTable,keyVars);
assert(numel(unique(matKeys))==numel(matKeys) && ...
    numel(unique(csvKeys))==numel(csvKeys), ...
    'femstudy:audit:DuplicateResultKey','Duplicate model/seed/case key in %s.',label);
[matSorted,mi]=sort(matKeys); [csvSorted,ci]=sort(csvKeys);
assert(isequal(matSorted,csvSorted),'femstudy:audit:ResultKeys', ...
    '%s CSV model/seed/case keys differ from MAT table.',label);
for col=1:numel(matTable.Properties.VariableNames)
    name=matTable.Properties.VariableNames{col};
    a=matTable.(name); b=csvTable.(name);
    if isnumeric(a) || islogical(a)
        a=double(a(mi)); b=double(b(ci));
        bothNaN=isnan(a)&isnan(b);
        sameInf=isinf(a)&isinf(b)&(sign(a)==sign(b));
        tolerance=1e-12*max(1,max(abs(a),abs(b)));
        equal=(abs(a-b)<=tolerance)|bothNaN|sameInf;
        assert(all(equal,'all'),'femstudy:audit:MetricMismatch', ...
            '%s metric/column `%s` differs between MAT and CSV.',label,name);
    else
        assert(isequal(string(a(mi)),string(b(ci))), ...
            'femstudy:audit:ValueMismatch', ...
            '%s values in column `%s` differ between MAT and CSV.',label,name);
    end
end
end

function out=keys(t,vars)
parts=strings(height(t),numel(vars));
for j=1:numel(vars)
    value=t.(vars{j});
    if isnumeric(value)
        parts(:,j)=compose('%.17g',double(value));
    else
        parts(:,j)=string(value);
    end
end
out=join(parts,"|",2);
end

