function net = sgdMomentum(XTrain, YTrain, layers, XValidation, YValidation, settings)
%sgdMomentum Train an MLP with stochastic gradient descent and momentum.

rng(settings.randomSeed);
validationFrequency = max(1, floor(size(XTrain, 1) / settings.miniBatchSize));

options = trainingOptions("sgdm", ...
    MaxEpochs=settings.maxEpochs, ...
    MiniBatchSize=settings.miniBatchSize, ...
    InitialLearnRate=settings.learningRate, ...
    Momentum=settings.momentum, ...
    Shuffle="every-epoch", ...
    ValidationData={XValidation, YValidation}, ...
    ValidationFrequency=validationFrequency, ...
    ValidationPatience=20, ...
    OutputNetwork="best-validation", ...
    ExecutionEnvironment="cpu", ...
    Verbose=false);

net = trainnet(XTrain, YTrain, layers, "mse", options);
end