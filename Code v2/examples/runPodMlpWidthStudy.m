function result = runPodMlpWidthStudy(outputDir)
%runPodMlpWidthStudy Compare two-hidden-layer POD-MLPs across widths.
%   Trains widths [16 20 32 40 64 80 100 128] with 768 cases and seeds
%   [42 43 44], using weighted_field_mse. All runs use the same existing
%   128-case validation split. No test data is loaded. Completed model and
%   metric checkpoints can be resumed with the same OUTPUTDIR.
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root);
if nargin<1
    outputDir=fullfile(root,'experiments','pod_mlp_width_study_20261109_with128');
end

dataDir=fullfile(root,'data_generation','data','static');
validationDir=fullfile(root,'experiments', ...
    'pod_mlp_fresh_validation_128_20261108','reference_data','static');
training=surrogate.loadDataset(fullfile(dataDir,'train.mat'));
validation=surrogate.loadDataset(fullfile(validationDir,'val.mat'));
surrogate.validateTrainingSplits(training,validation);
assert(numel(training.caseIds)>=768 && numel(validation.caseIds)==128, ...
    'surrogate:widthStudy:DataCount', ...
    'Expected at least 768 training cases and exactly 128 validation cases.');

widths=[16 20 32 40 64 80 100 128];
depth=2;
trainingCases=768;
seeds=[42 43 44];
lossMode="weighted_field_mse";
datasetId="static-data-generation-v1";
config=struct('datasetId',datasetId,'trainingCaseIds',training.caseIds, ...
    'validationDatasetId',"static-fresh-validation-v1-seed20261109-n128", ...
    'validationCaseIds',validation.caseIds,'widths',widths, ...
    'hiddenLayers',depth,'trainingCases',trainingCases,'seeds',seeds, ...
    'lossMode',lossMode,'rank',10,'maxEpochs',200,'miniBatchSize',32, ...
    'learningRate',1e-3,'optimizer',"adam",'activation',"tanh", ...
    'validationPreviouslyUsedForModelComparison',true, ...
    'testDataLoaded',false,'matlabVersion',string(version));

if isfolder(outputDir) || isfile(outputDir)
    assert(isfolder(outputDir) && ...
        isfile(fullfile(outputDir,'study_config.mat')), ...
        'surrogate:widthStudy:ExistingOutput', ...
        'Existing output is not a resumable width study: %s',outputDir);
    saved=load(fullfile(outputDir,'study_config.mat'),'config');
    assert(isequaln(saved.config,config), ...
        'surrogate:widthStudy:ConfigMismatch', ...
        'Output folder belongs to a different study configuration.');
else
    [created,message]=mkdir(outputDir);
    assert(created,'surrogate:widthStudy:Directory', ...
        'Cannot create output: %s',message);
    save(fullfile(outputDir,'study_config.mat'),'config');
end

summaryPath=fullfile(outputDir,'model_metrics.csv');
caseErrorsPath=fullfile(outputDir,'validation_case_errors.csv');
if isfile(summaryPath)
    modelMetrics=readtable(summaryPath,'TextType','string');
else
    modelMetrics=emptyModelMetrics();
end
if isfile(caseErrorsPath)
    caseErrors=readtable(caseErrorsPath,'TextType','string');
else
    caseErrors=emptyCaseErrors();
end

freeze=table(repelem(widths(:),numel(seeds)), ...
    repmat(depth,numel(widths)*numel(seeds),1), ...
    repmat(trainingCases,numel(widths)*numel(seeds),1), ...
    repmat(seeds(:),numel(widths),1), ...
    'VariableNames',{'Width','HiddenLayers','TrainingCases','Seed'});
writetable(freeze,fullfile(outputDir,'study_plan.csv'));
writeText(fullfile(outputDir,'STUDY_SCOPE.txt'), ...
    "Exploratory validation study; model selection uses only the existing "+ ...
    "128-case validation split (IDs "+string(min(validation.caseIds))+"-"+ ...
    string(max(validation.caseIds))+"). These validation cases were already "+ ...
    "used for model comparisons. The separate 128-case test split is not read."+newline+ ...
    "Fixed: weighted_field_mse, two hidden tanh layers, rank 10, Adam, "+ ...
    "learning rate 0.001, 200 epochs, 768 training cases, seeds 42/43/44."+newline+ ...
    "Widths per hidden layer: "+join(string(widths),", ")+".");

request=struct('inputParameters',validation.inputParameters, ...
    'parameterNames',validation.parameterNames, ...
    'parameterUnits',validation.parameterUnits,'caseIds',validation.caseIds);
metricConfig=struct('staticReferenceFloor',0,'frequencyReferenceFloorHz',0);
modelDir=fullfile(outputDir,'models');
if ~isfolder(modelDir), mkdir(modelDir); end

for width=widths
    for seed=seeds
        existing=modelMetrics.Width==width & modelMetrics.Seed==seed;
        modelFile=fullfile(modelDir,sprintf( ...
            'pod_mlp_weighted_width_%d_layers_2_n768_seed%d.mat',width,seed));
        if any(existing)
            assert(nnz(existing)==1 && isfile(modelFile) && ...
                nnz(caseErrors.Width==width & caseErrors.Seed==seed)== ...
                numel(validation.caseIds), ...
                'surrogate:widthStudy:Checkpoint', ...
                'Incomplete checkpoint for width %d, seed %d.',width,seed);
            model=surrogate.loadModel(modelFile);
            assert(isequal(model.trainingCaseIds, ...
                trainingIdsForSeed(training,seed,trainingCases)) && ...
                isequaln(model.config,modelConfig(width,seed,datasetId, ...
                    depth,trainingCases,lossMode)), ...
                'surrogate:widthStudy:ModelConflict', ...
                'Checkpoint model does not match the study: %s',modelFile);
            continue
        end

        model=loadOrTrainModel(modelFile,training,width,depth, ...
            trainingCases,seed,datasetId,lossMode);
        assert(isequal(model.trainingCaseIds, ...
            trainingIdsForSeed(training,seed,trainingCases)), ...
            'surrogate:widthStudy:TrainingIds', ...
            'Model training IDs differ from the study plan: %s',modelFile);
        prediction=surrogate.predictModel(model,request);
        metrics=surrogate.evaluatePrediction(prediction,validation,metricConfig);
        relative=sort(metrics.relativeWeightedFieldError( ...
            metrics.relativeErrorDefined));
        assert(numel(relative)==numel(validation.caseIds), ...
            'surrogate:widthStudy:RelativeErrors', ...
            'Expected one defined relative error per validation case.');
        run=table(width,depth,trainingCases,seed, ...
            mean(metrics.absoluteWeightedFieldError), ...
            100*median(relative),100*relative(ceil(.95*numel(relative))), ...
            nnz(~metrics.relativeErrorDefined), ...
            'VariableNames',modelMetrics.Properties.VariableNames);
        modelMetrics=[modelMetrics;run]; %#ok<AGROW>
        block=table(repmat(width,numel(validation.caseIds),1), ...
            repmat(depth,numel(validation.caseIds),1), ...
            repmat(trainingCases,numel(validation.caseIds),1), ...
            repmat(seed,numel(validation.caseIds),1),validation.caseIds, ...
            metrics.absoluteWeightedFieldError, ...
            metrics.referenceWeightedFieldNorm, ...
            metrics.relativeWeightedFieldError, ...
            'VariableNames',caseErrors.Properties.VariableNames);
        caseErrors=[caseErrors;block]; %#ok<AGROW>
        writetable(modelMetrics,summaryPath);
        writetable(caseErrors,caseErrorsPath);
        fprintf('Completed width %d, 2 layers, seed %d.\n',width,seed);
    end
end

modelMetrics=sortrows(modelMetrics,{'Width','Seed'});
caseErrors=sortrows(caseErrors,{'Width','Seed','CaseId'});
writetable(modelMetrics,summaryPath);
writetable(caseErrors,caseErrorsPath);
summaryByWidth=aggregateByWidth(modelMetrics,widths,seeds);
writetable(summaryByWidth,fullfile(outputDir,'summary_by_width.csv'));
modelManifest=makeModelManifest(modelDir,widths,seeds);
writetable(modelManifest,fullfile(outputDir,'model_manifest.csv'));
save(fullfile(outputDir,'width_study_results.mat'), ...
    'config','modelMetrics','caseErrors','summaryByWidth','modelManifest', ...
    'metricConfig','-v7.3');
plotWidthStudy(modelMetrics,caseErrors,widths,seeds,outputDir);
result=struct('modelMetrics',modelMetrics,'caseErrors',caseErrors, ...
    'summaryByWidth',summaryByWidth,'modelManifest',modelManifest, ...
    'outputDir',string(outputDir));
end

function model=loadOrTrainModel(file,training,width,depth,count,seed,datasetId,lossMode)
config=modelConfig(width,seed,datasetId,depth,count,lossMode);
if isfile(file)
    model=surrogate.loadModel(file);
    expectedIds=trainingIdsForSeed(training,seed,count);
    assert(isequal(model.trainingCaseIds,expectedIds) && ...
        isequaln(model.config,config), ...
        'surrogate:widthStudy:ModelConflict', ...
        'Existing model does not match the requested run: %s',file);
    return
end
subset=training;
[found,indices]=ismember(trainingIdsForSeed(training,seed,count), ...
    training.caseIds);
assert(all(found) && numel(indices)==count, ...
    'surrogate:widthStudy:TrainingIds','Could not resolve requested training IDs.');
subset.caseIds=training.caseIds(indices);
subset.inputParameters=training.inputParameters(indices,:);
subset.displacementFields=training.displacementFields(:,indices);
subset=rmfield(subset,{'computationTimeSeconds','tipDisplacementZ', ...
    'maxDisplacementMagnitudeOnGrid','meshNodeCounts'});
fprintf('Training width %d, 2 layers, %d cases, seed %d.\n', ...
    width,count,seed);
[model,~]=surrogate.fitModel("pod_mlp",subset,config);
surrogate.saveModel(file,model);
end

function config=modelConfig(width,seed,datasetId,depth,count,lossMode)
config=struct('seed',seed,'datasetId',datasetId,'rank',10, ...
    'hiddenWidth',width,'maxEpochs',200,'miniBatchSize',min(32,count), ...
    'learningRate',1e-3,'hiddenLayers',depth,'lossMode',lossMode);
end

function ids=trainingIdsForSeed(training,seed,count)
stream=RandStream('mt19937ar','Seed',seed);
originalCount=min(384,numel(training.caseIds));
order=[randperm(stream,originalCount), ...
    originalCount+randperm(stream,numel(training.caseIds)-originalCount)];
ids=training.caseIds(order(1:count));
end

function T=emptyModelMetrics()
T=table('Size',[0 8], ...
    'VariableTypes',{'double','double','double','double', ...
        'double','double','double','double'}, ...
    'VariableNames',{'Width','HiddenLayers','TrainingCases','Seed', ...
        'MeanAbsoluteErrorM','MedianRelativePercent','P95RelativePercent', ...
        'UndefinedCount'});
end

function T=emptyCaseErrors()
T=table('Size',[0 8], ...
    'VariableTypes',{'double','double','double','double', ...
        'double','double','double','double'}, ...
    'VariableNames',{'Width','HiddenLayers','TrainingCases','Seed','CaseId', ...
        'AbsoluteErrorM','ReferenceNormM','RelativeError'});
end

function output=aggregateByWidth(runs,widths,seeds)
output=table();
for width=widths
    rows=runs(runs.Width==width,:);
    assert(height(rows)==numel(seeds), ...
        'surrogate:widthStudy:RunCount', ...
        'Expected one completed run per seed at width %d.',width);
    output=[output;table(width,height(rows), ...
        median(rows.MeanAbsoluteErrorM), ...
        median(rows.MedianRelativePercent), ...
        median(rows.P95RelativePercent), ...
        min(rows.MedianRelativePercent),max(rows.MedianRelativePercent), ...
        min(rows.P95RelativePercent),max(rows.P95RelativePercent), ...
        'VariableNames',{'Width','SeedCount','MeanAbsoluteErrorM_medianOfSeeds', ...
            'MedianRelativePercent_medianOfSeeds', ...
            'P95RelativePercent_medianOfSeeds', ...
            'MedianRelativePercent_minSeed','MedianRelativePercent_maxSeed', ...
            'P95RelativePercent_minSeed','P95RelativePercent_maxSeed'})]; %#ok<AGROW>
end
end

function manifest=makeModelManifest(modelDir,widths,seeds)
manifest=table();
for width=widths
    for seed=seeds
        file=fullfile(modelDir,sprintf( ...
            'pod_mlp_weighted_width_%d_layers_2_n768_seed%d.mat',width,seed));
        manifest=[manifest;table(width,2,768,seed,string(file),sha256File(file), ...
            'VariableNames',{'Width','HiddenLayers','TrainingCases','Seed', ...
                'File','SHA256'})]; %#ok<AGROW>
    end
end
end

function plotWidthStudy(runs,cases,widths,seeds,outputDir)
colors=lines(numel(seeds));
fig=figure('Visible','off','Position',[100 100 1500 500]);
tiled=tiledlayout(fig,1,3,'TileSpacing','compact','Padding','compact');
metrics={'MeanAbsoluteErrorM','MedianRelativePercent','P95RelativePercent'};
labels={'Mittlerer absoluter Feldfehler [m]', ...
    'Median relativer Feldfehler [%]','P95 relativer Feldfehler [%]'};
titles={'Absolutfehler','Medianfehler','P95-Fehler'};
for metric=1:numel(metrics)
    ax=nexttile(tiled); hold(ax,'on');
    for k=1:numel(seeds)
        values=zeros(size(widths));
        for j=1:numel(widths)
            row=runs.Width==widths(j) & runs.Seed==seeds(k);
            assert(nnz(row)==1,'surrogate:widthStudy:PlotData', ...
                'Missing run for width %d and seed %d.',widths(j),seeds(k));
            values(j)=runs.(metrics{metric})(row);
        end
        semilogy(ax,widths,values,'-o','Color',colors(k,:), ...
            'LineWidth',1.2,'DisplayName',sprintf('Seed %d',seeds(k)));
    end
    medians=zeros(size(widths));
    for j=1:numel(widths)
        rows=runs.Width==widths(j);
        medians(j)=median(runs.(metrics{metric})(rows));
    end
    semilogy(ax,widths,medians,'-ks','LineWidth',2, ...
        'MarkerFaceColor','k','DisplayName','Median über Seeds');
    grid(ax,'on'); xticks(ax,widths); xtickangle(ax,45);
    xlabel(ax,'Neuronen je versteckter Schicht');
    ylabel(ax,labels{metric}); title(ax,titles{metric});
    if metric==1, legend(ax,'Location','best'); end
end
title(tiled,'POD-MLP: Fehler nach Netzbreite (2 versteckte Schichten)');
savefig(fig,fullfile(outputDir,'error_by_width.fig'));
exportgraphics(fig,fullfile(outputDir,'error_by_width.png'),'Resolution',160);
close(fig);

caseMedian=table();
for width=widths
    for caseId=unique(cases.CaseId)'
        rows=cases.Width==width & cases.CaseId==caseId;
        assert(nnz(rows)==numel(seeds), ...
            'surrogate:widthStudy:CasePlotData', ...
            'Expected one case error per seed for width %d, case %d.', ...
            width,caseId);
        caseMedian=[caseMedian;table(width,caseId, ...
            median(cases.RelativeError(rows))*100, ...
            median(cases.AbsoluteErrorM(rows)), ...
            'VariableNames',{'Width','CaseId','MedianRelativePercent', ...
                'MedianAbsoluteErrorM'})]; %#ok<AGROW>
    end
end
fig=figure('Visible','off','Position',[100 100 1400 650]);
tiled=tiledlayout(fig,2,1,'TileSpacing','compact','Padding','compact');
caseColors=lines(numel(widths));
for metric=1:2
    ax=nexttile(tiled); hold(ax,'on');
    if metric==1
        field='MedianRelativePercent'; label='Relativer Feldfehler [%]';
        titleText='Relativer Fehler je Validierungsfall (Seed-Median)';
    else
        field='MedianAbsoluteErrorM'; label='Absoluter Feldfehler [m]';
        titleText='Absoluter Fehler je Validierungsfall (Seed-Median)';
    end
    for j=1:numel(widths)
        rows=caseMedian.Width==widths(j);
        [ids,order]=sort(caseMedian.CaseId(rows));
        values=caseMedian.(field)(rows);
        values=values(order);
        semilogy(ax,1:numel(ids),values,'-','Color',caseColors(j,:), ...
            'LineWidth',1,'DisplayName',sprintf('%d Neuronen',widths(j)));
    end
    grid(ax,'on'); xlim(ax,[1 numel(unique(caseMedian.CaseId))]);
    xlabel(ax,'Validierungsfall'); ylabel(ax,label); title(ax,titleText);
    if metric==1, legend(ax,'Location','eastoutside'); end
end
title(tiled,'Fehlerverlauf über 128 bereits verwendete Validierungsfälle');
savefig(fig,fullfile(outputDir,'error_by_case.fig'));
exportgraphics(fig,fullfile(outputDir,'error_by_case.png'),'Resolution',160);
close(fig);
end

function hash=sha256File(file)
fid=fopen(file,'rb');
assert(fid>=0,'surrogate:widthStudy:HashRead','Cannot open model: %s',file);
cleanup=onCleanup(@()fclose(fid));
bytes=fread(fid,Inf,'*uint8');
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
hash=lower(string(reshape(dec2hex( ...
    typecast(digest.digest(),'uint8'),2).',1,[])));
clear cleanup
end

function writeText(file,text)
fid=fopen(file,'w');
assert(fid>=0,'surrogate:widthStudy:Write','Cannot write file: %s',file);
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,char(text),'char');
clear cleanup
end
