function studyCheckFrozen(out)
% Validate the study freeze and every listed file before test access.
manifest=fullfile(out,'freeze_manifest.csv'); seal=fullfile(out,'freeze_manifest.sha256');
assert(isfile(manifest) && isfile(seal),'study:FreezeRequired','Verified freeze required before test access.');
assert(strcmp(studyHash(manifest),strtrim(fileread(seal))),'study:FreezeChanged','Freeze manifest changed.');
T=readtable(manifest,'TextType','string','Delimiter',',','ReadVariableNames',true,'VariableNamingRule','preserve');
assert(height(T)>=5 && all(ismember({'Path','SHA256'},T.Properties.VariableNames)), ...
    'study:FreezeInvalid','Invalid freeze manifest.');
required=[string(fullfile(out,'source_manifest.csv'));string(fullfile(out,'candidate_design.mat')); ...
    string(fullfile(out,'selections.mat'));string(fullfile(out,'training.complete')); ...
    string(fullfile(out,'references','val','val.mat')); ...
    string(fullfile(out,'references','interpolation','test.mat')); ...
    string(fullfile(out,'references','extrapolation','test.mat'))];
assert(all(ismember(required,T.Path)),'study:FreezeInvalid','Freeze is missing required study artifacts.');
assert(any(contains(T.Path,fullfile('runs',filesep))) || any(contains(T.Path,filesep+"runs"+filesep)), ...
    'study:FreezeInvalid','Freeze contains no pipeline runs.');
for k=1:height(T)
    assert(isfile(T.Path(k)) && strcmp(studyHash(T.Path(k)),T.SHA256(k)), ...
        'study:FreezeChanged','Frozen artifact changed or missing: %s',T.Path(k));
end
end
