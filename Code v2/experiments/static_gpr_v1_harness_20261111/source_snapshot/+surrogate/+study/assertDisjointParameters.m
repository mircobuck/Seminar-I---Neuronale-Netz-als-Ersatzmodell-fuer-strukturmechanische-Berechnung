function assertDisjointParameters(first,second,lower,upper,tolerance)
%assertDisjointParameters Reject parameter duplicates in normalized space.
lower=reshape(double(lower),1,[]); span=reshape(double(upper),1,[])-lower;
assert(isnumeric(first) && isnumeric(second) && isreal(first) && isreal(second) && ...
    size(first,2)==numel(span) && size(second,2)==numel(span) && ...
    all(isfinite(first),'all') && all(isfinite(second),'all') && ...
    all(isfinite(span) & span>0) && isscalar(tolerance) && isfinite(tolerance) && tolerance>=0, ...
    'surrogate:study:ParameterInput','Invalid parameters, scales or tolerance.');
first=(double(first)-lower)./span; second=(double(second)-lower)./span;
for k=1:size(first,1)
    matches=all(abs(second-first(k,:))<=tolerance,2);
    assert(~any(matches),'surrogate:study:ParameterOverlap', ...
        'Parameter row %d overlaps the comparison set within tolerance.',k);
end
end
