function result = runWeightedLossIndependentTest(outputRoot,designSeed,idStart)
%runWeightedLossIndependentTest Freeze the selected weighted-loss models and test them.
%   Generates 128 new static test FEM cases, then evaluates the three
%   768-case, 64-neuron, two-hidden-layer weighted_field_mse models (seeds
%   42/43/44). Model selection and hashes are recorded before test labels.
%
%   OUTPUTROOT must not already exist. Optional DESIGNSEED and IDSTART
%   default to 20261110 and 814001.
projectRoot=fileparts(fileparts(fileparts(mfilename('fullpath'))));
studyRoot=fullfile(projectRoot,'studies','static_final_evaluation');
addpath(projectRoot,studyRoot,fullfile(projectRoot,'scripts','matlab'));
if nargin<1
    outputRoot=fullfile(projectRoot,'experiments', ...
        'pod_mlp_weighted_independent_test_20261109');
end
if nargin<2, designSeed=20261110; end
if nargin<3, idStart=814001; end
assert(isnumeric(designSeed) && isscalar(designSeed) && isfinite(designSeed) && ...
    designSeed>=0 && designSeed==fix(designSeed) && ...
    isnumeric(idStart) && isscalar(idStart) && isfinite(idStart) && ...
    idStart>=1 && idStart==fix(idStart), ...
    'surrogate:weightedIndependentTest:Arguments', ...
    'designSeed and idStart must be valid integers (idStart positive).');
assert(~isfolder(outputRoot) && ~isfile(outputRoot), ...
    'surrogate:weightedIndependentTest:Exists', ...
    'Output path already exists: %s',outputRoot);

% Freeze the validation-selected architecture and all three existing seeds.
width=64; depth=2; trainingCases=768; seeds=[42 43 44];
modelRoot=fullfile(projectRoot,'experiments', ...
    'pod_mlp_loss_study_20261107','models');
records=repmat(struct('Label',"",'File',"",'SHA256',"", ...
    'Seed',0,'TrainingCaseIds',[]),numel(seeds),1);
for k=1:numel(seeds)
    seed=seeds(k);
    file=fullfile(modelRoot,sprintf( ...
        'pod_mlp_weighted_%d_width_%d_layers_n%d_seed%d.mat', ...
        width,depth,trainingCases,seed));
    assert(isfile(file),'surrogate:weightedIndependentTest:ModelMissing', ...
        'Missing selected model: %s',file);
    model=surrogate.loadModel(file);
    layerClasses=string(arrayfun(@class,model.state.network.Layers, ...
        'UniformOutput',false));
    assert(string(model.methodId)=="pod_mlp" && string(model.task)=="static" && ...
        string(model.state.lossMode)=="weighted_field_mse" && ...
        model.config.hiddenWidth==width && model.config.hiddenLayers==depth && ...
        model.config.rank==10 && model.config.maxEpochs==200 && ...
        model.config.seed==seed && numel(model.trainingCaseIds)==trainingCases && ...
        nnz(layerClasses=="nnet.cnn.layer.TanhLayer")==depth, ...
        'surrogate:weightedIndependentTest:ModelConfig', ...
        'Selected model does not match the frozen study configuration: %s',file);
    records(k)=struct('Label',sprintf( ...
        "POD_MLP_WEIGHTED_FIELD_MSE_64_NEURONS_2_LAYERS_N768_SEED%d",seed), ...
        'File',string(file),'SHA256',sha256File(file), ...
        'Seed',seed,'TrainingCaseIds',model.trainingCaseIds(:)');
end

if ~isfolder(outputRoot)
    [created,message]=mkdir(outputRoot);
    assert(created,'surrogate:weightedIndependentTest:Directory', ...
        'Cannot create output directory: %s',message);
end
referenceRoot=fullfile(outputRoot,'reference_data');
evaluationRoot=fullfile(outputRoot,'evaluation');
selection="weighted_field_mse; width 64; two hidden tanh layers; POD rank 10; "+ ...
    "768 training cases; seeds 42, 43, and 44. This architecture was selected "+ ...
    "using the previously reported validation results; no results from this test "+ ...
    "set will be used for model selection.";
freezeMetadata=struct('selectionRule',selection,'modelRecords',records, ...
    'caseCount',128,'designSeed',designSeed,'idStart',idStart, ...
    'createdBeforeTestLabels',true,'matlabVersion',string(version), ...
    'createdAt',string(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ssXXX')));
freezeTable=struct2table(rmfield(records,'TrainingCaseIds'));
writetable(freezeTable,fullfile(outputRoot,'model_freeze.csv'));
save(fullfile(outputRoot,'model_freeze.mat'),'freezeMetadata','-v7.3');
writeText(fullfile(outputRoot,'FREEZE_BEFORE_LABELS.txt'), ...
    "Created before generating new test FEM labels."+newline+ ...
    "Selection: "+selection+newline+ ...
    "Test design: 128 static Latin-hypercube cases, seed "+string(designSeed)+ ...
    ", IDs "+string(idStart)+"-"+string(idStart+127)+"."+newline+ ...
    "Model SHA-256 hashes:"+newline+ ...
    strjoin(string({records.Label})+" "+string({records.SHA256}),newline)+newline);

dataConfig=jsondecode(fileread(fullfile(projectRoot,'data_generation', ...
    'configs','data_generation_v1.json')));
dataConfig.seed=designSeed;
dataConfig.static.idStart=idStart;
dataConfig.static.counts.train=0;
dataConfig.static.counts.val=0;
dataConfig.static.counts.test=128;
configPath=fullfile(outputRoot,'fresh_test_data_config.json');
writeText(configPath,string(jsonencode(dataConfig)));
run_data_generation_v2("design",configPath,referenceRoot);

designPath=fullfile(referenceRoot,'static','design.csv');
freshDesign=readtable(designPath,'TextType','string');
assert(height(freshDesign)==128 && all(freshDesign.split=="test") && ...
    numel(unique(freshDesign.id))==128, ...
    'surrogate:weightedIndependentTest:Design', ...
    'Expected exactly 128 unique static test cases.');
knownDesigns={ ...
    fullfile(projectRoot,'data_generation','data','static','design.csv'), ...
    fullfile(projectRoot,'data_generation','data','static','backup_384','design.csv'), ...
    fullfile(projectRoot,'experiments','pod_mlp_independent_test_20261106', ...
        'reference_data','static','design.csv'), ...
    fullfile(projectRoot,'experiments','pod_mlp_fresh_validation_20261108', ...
        'reference_data','static','design.csv'), ...
    fullfile(projectRoot,'experiments','pod_mlp_fresh_validation_128_20261108', ...
        'reference_data','static','design.csv')};
parameterNames=freshDesign.Properties.VariableNames( ...
    ~ismember(freshDesign.Properties.VariableNames,{'id','split'}));
for k=1:numel(knownDesigns)
    if isfile(knownDesigns{k})
        previous=readtable(knownDesigns{k},'TextType','string');
        assert(isempty(intersect(freshDesign.id,previous.id)) && ...
            ~any(ismember(freshDesign{:,parameterNames}, ...
            previous{:,parameterNames},'rows')), ...
            'surrogate:weightedIndependentTest:DesignOverlap', ...
            'Fresh test design overlaps an existing design: %s',knownDesigns{k});
    end
end
fprintf('Frozen %d models; generating fresh FEM labels for 128 test cases.\n', ...
    numel(records));
run_data_generation_v2("static_test",configPath,referenceRoot);

testData=surrogate.loadDataset(fullfile(referenceRoot,'static','test.mat'));
assert(string(testData.split)=="test" && numel(testData.caseIds)==128 && ...
    isempty(intersect(testData.caseIds, ...
        vertcat(records.TrainingCaseIds))), ...
    'surrogate:weightedIndependentTest:Dataset', ...
    'Generated test data is incomplete or overlaps model training cases.');
surrogate.validateDataset(testData);

models=repmat(struct('label',"",'file',""),numel(records),1);
for k=1:numel(records)
    assert(sha256File(records(k).File)==records(k).SHA256, ...
        'surrogate:weightedIndependentTest:ModelChanged', ...
        'A frozen model changed after test FEM generation: %s',records(k).File);
    models(k)=struct('label',records(k).Label,'file',records(k).File);
end
config=studyConfigTemplate();
config.datasetFile=fullfile(referenceRoot,'static','test.mat');
config.datasetId="static-independent-lhs-v1-seed"+string(designSeed)+"-n128";
config.selectionRule=selection;
config.freezeDescription="Three preselected weighted_field_mse models, 64 neurons, "+ ...
    "two hidden layers, 768 training cases, seeds 42/43/44. Their SHA-256 "+ ...
    "hashes and configurations were recorded before test FEM labels.";
config.testLabelHistory="The existing 64-case static test set was previously used "+ ...
    "for evaluating older models. These 128 new cases use fresh IDs and a fresh "+ ...
    "Latin-hypercube design, are nonoverlapping with the known static designs, "+ ...
    "and were generated only after the selected models were frozen.";
config.metricConfig.staticReferenceFloor=0;
config.models=models;
result=runStaticFinalEvaluation(config,evaluationRoot,false);
assert(numel(result.metadata.caseIds)==128 && ...
    all(result.summary.Status=="complete"), ...
    'surrogate:weightedIndependentTest:Incomplete', ...
    'Independent evaluation incomplete; inspect evaluation/run_status.csv.');
end

function hash=sha256File(file)
fid=fopen(file,'rb');
assert(fid>=0,'surrogate:weightedIndependentTest:HashRead', ...
    'Cannot open model: %s',file);
cleanup=onCleanup(@()fclose(fid));
bytes=fread(fid,Inf,'*uint8');
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
hash=lower(string(reshape(dec2hex( ...
    typecast(digest.digest(),'uint8'),2).',1,[])));
clear cleanup
end

function writeText(file,text)
fid=fopen(file,'w');
assert(fid>=0,'surrogate:weightedIndependentTest:Write', ...
    'Cannot write file: %s',file);
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,char(text),'char');
clear cleanup
end
