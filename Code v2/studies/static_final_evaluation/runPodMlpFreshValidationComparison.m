function result = runPodMlpFreshValidationComparison(outputDir,caseCount,designSeed,idStart)
%runPodMlpFreshValidationComparison Compare frozen old/new-loss models on new FEM cases.
%   Evaluates the 210 historical per_coefficient_mse models and 210
%   weighted_field_mse models on newly generated static validation cases.
%   All model files are checked and SHA-256 frozen before reference labels are
%   generated. No model is retrained and no test split is loaded.
%
%   This is a validation comparison, not a final independent test. The new
%   cases are generated with the existing static FEM configuration, and all
%   frozen models use identical input cases and metric definitions. Optional
%   arguments are OUTPUTDIR, CASECOUNT, DESIGNSEED, and IDSTART.

% Resolve project and workspace roots relative to this script. Historical
% learning-curve models were saved in the workspace-level experiment folders,
% while the 768-case models and new-loss models live under Code v2.
projectRoot=fileparts(fileparts(fileparts(mfilename('fullpath'))));
workspaceRoot=fileparts(fileparts(projectRoot));
studyRoot=fullfile(projectRoot,'studies','static_final_evaluation');
addpath(projectRoot,studyRoot,fullfile(projectRoot,'scripts','matlab'));
if nargin<1
    outputDir=fullfile(projectRoot,'experiments','pod_mlp_fresh_validation_20261108');
end
if nargin<2, caseCount=12; end
if nargin<3, designSeed=20261108; end
if nargin<4, idStart=812001; end
assert(isnumeric(caseCount) && isscalar(caseCount) && isfinite(caseCount) && ...
    caseCount>=1 && caseCount==fix(caseCount) && ...
    isnumeric(designSeed) && isscalar(designSeed) && isfinite(designSeed) && ...
    designSeed>=0 && designSeed==fix(designSeed) && ...
    isnumeric(idStart) && isscalar(idStart) && isfinite(idStart) && ...
    idStart>=1 && idStart==fix(idStart), ...
    'surrogate:freshValidation:Arguments', ...
    'caseCount, designSeed, and idStart must be valid nonnegative integers (idStart positive).');
assert(~isfolder(outputDir) && ~isfile(outputDir), ...
    'surrogate:freshValidation:Exists','Output path already exists: %s',outputDir);

% Define the complete paired comparison before generating any new FEM labels.
widths=[64 128]; depths=1:5;
trainingCounts=[12 24 48 96 192 384 768]; seeds=[42 43 44];
lossModes=["per_coefficient_mse","weighted_field_mse"];
modelCount=numel(widths)*numel(depths)*numel(trainingCounts)*numel(seeds)*numel(lossModes);

% The old-loss manifest is the source of truth for historical models with up
% to 384 training cases. The old 768-case stage has a separate stable layout.
oldManifestPath=fullfile(projectRoot,'experiments', ...
    'pod_mlp_layer_comparison_20261105','POD_MLP_Versuchsprotokoll', ...
    'alle_versuchslaeufe.csv');
assert(isfile(oldManifestPath),'surrogate:freshValidation:OldManifest', ...
    'Cannot find historical model manifest: %s',oldManifestPath);
oldManifest=readtable(oldManifestPath,'TextType','string');
oldManifest=oldManifest(ismember(oldManifest.NeuronsPerLayer,widths) & ...
    ismember(oldManifest.HiddenLayers,depths) & ...
    ismember(oldManifest.TrainingCases,trainingCounts(1:end-1)) & ...
    ismember(oldManifest.Seed,seeds),:);
assert(height(oldManifest)==numel(widths)*numel(depths)* ...
    (numel(trainingCounts)-1)*numel(seeds), ...
    'surrogate:freshValidation:OldManifestCount', ...
    'Historical manifest does not contain all 180 expected old-loss models.');

newModelRoot=fullfile(projectRoot,'experiments','pod_mlp_loss_study_20261107','models');
old768Root=fullfile(projectRoot,'experiments','static_768_20261105');
modelRecords=repmat(struct('LossMode',"",'Width',0,'HiddenLayers',0, ...
    'TrainingCases',0,'Seed',0,'File',"",'SHA256',"",'TrainingCaseIds',[]), ...
    modelCount,1);
recordIndex=0;

% Resolve, load, validate, and hash every model before creating test-like
% reference labels. Paired losses must have exactly the same training IDs.
for width=widths
    for depth=depths
        for count=trainingCounts
            for seed=seeds
                if count<768
                    match=oldManifest.NeuronsPerLayer==width & ...
                        oldManifest.HiddenLayers==depth & ...
                        oldManifest.TrainingCases==count & oldManifest.Seed==seed;
                    assert(nnz(match)==1,'surrogate:freshValidation:OldModelRecord', ...
                        'Expected one old model record for width %d, depth %d, n %d, seed %d.', ...
                        width,depth,count,seed);
                    oldFile=fullfile(workspaceRoot,oldManifest.ModelFile(match));
                else
                    oldFile=fullfile(old768Root,sprintf('width_%d_layers_%d',width,depth), ...
                        sprintf('pod_mlp_adam_%d_n768_seed%d.mat',width,seed));
                end
                newFile=fullfile(newModelRoot,sprintf( ...
                    'pod_mlp_weighted_%d_width_%d_layers_n%d_seed%d.mat', ...
                    width,depth,count,seed));
                files=[string(oldFile);string(newFile)];
                for lossIndex=1:numel(lossModes)
                    recordIndex=recordIndex+1;
                    file=files(lossIndex);
                    assert(isfile(file),'surrogate:freshValidation:ModelMissing', ...
                        'Missing frozen model: %s',file);
                    model=surrogate.loadModel(file);
                    assert(string(model.methodId)=="pod_mlp" && ...
                        string(model.task)=="static" && ...
                        numel(model.trainingCaseIds)==count, ...
                        'surrogate:freshValidation:ModelContract', ...
                        'Model metadata or training count does not match: %s',file);
                    if lossIndex==1
                        assert(~isfield(model.state,'lossMode') || ...
                            string(model.state.lossMode)=="per_coefficient_mse", ...
                            'surrogate:freshValidation:OldLossMode', ...
                            'Historical model is not using the old loss: %s',file);
                            trainingIds=model.trainingCaseIds;
                    else
                        assert(string(model.state.lossMode)=="weighted_field_mse", ...
                            'surrogate:freshValidation:NewLossMode', ...
                            'New model does not use weighted_field_mse: %s',file);
                        assert(isequal(model.trainingCaseIds,trainingIds), ...
                            'surrogate:freshValidation:TrainingIdMismatch', ...
                            'Old and new loss models do not use identical training IDs: %s',file);
                    end
                    layerClasses=string(arrayfun(@class,model.state.network.Layers, ...
                        'UniformOutput',false));
                    assert(model.config.hiddenWidth==width && ...
                        nnz(layerClasses=="nnet.cnn.layer.TanhLayer")==depth && ...
                        model.config.rank==10 && model.config.maxEpochs==200, ...
                        'surrogate:freshValidation:ModelSettings', ...
                        'Frozen model architecture/settings do not match the study: %s',file);
                    modelRecords(recordIndex)=struct('LossMode',lossModes(lossIndex), ...
                        'Width',width,'HiddenLayers',depth,'TrainingCases',count, ...
                        'Seed',seed,'File',file,'SHA256',sha256File(file), ...
                        'TrainingCaseIds',model.trainingCaseIds(:)');
                end
            end
        end
    end
end
assert(recordIndex==modelCount, ...
    'surrogate:freshValidation:ModelCount','Expected to freeze all 420 models.');

% Persist the frozen artifact manifest before generating the new validation
% labels. This records the exact model files, hashes, settings, and training
% IDs used for the subsequent comparison.
if ~isfolder(outputDir)
    [created,message]=mkdir(outputDir);
    assert(created,'surrogate:freshValidation:Directory', ...
        'Cannot create output directory: %s',message);
end
freezeTable=struct2table(rmfield(modelRecords,'TrainingCaseIds'));
trainingIdText=strings(numel(modelRecords),1);
for i=1:numel(modelRecords)
    trainingIdText(i)=strjoin(string(modelRecords(i).TrainingCaseIds),';');
end
freezeTable.TrainingCaseIds=trainingIdText;
writetable(freezeTable,fullfile(outputDir,'model_freeze.csv'));
freezeMetadata=struct('createdBeforeNewValidationLabels',true, ...
    'lossModes',lossModes,'widths',widths,'depths',depths, ...
    'trainingCounts',trainingCounts,'seeds',seeds, ...
    'modelCount',modelCount,'oldManifest',string(oldManifestPath), ...
    'testDataLoaded',false,'matlabVersion',string(version), ...
    'createdAt',string(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ssXXX')));
save(fullfile(outputDir,'model_freeze.mat'),'modelRecords','freezeMetadata','-v7.3');
writeFreezeNote(fullfile(outputDir,'FREEZE_BEFORE_LABELS.txt'), ...
    freezeMetadata, ...
    "All 210 historical per_coefficient_mse and 210 weighted_field_mse models were resolved, loaded, configuration-checked, pair-checked for identical training IDs, and SHA-256 hashed before generating new validation FEM labels.");

% Create a new, validation-only design in a dedicated output folder. It uses
% the established parameter bounds and a fresh seed/ID range, not the existing
% training, validation, or test designs.
referenceRoot=fullfile(outputDir,'reference_data');
configPath=fullfile(outputDir,'fresh_validation_data_config.json');
dataConfig=jsondecode(fileread(fullfile(projectRoot, ...
    'data_generation','configs','data_generation_v1.json')));
dataConfig.seed=designSeed;
dataConfig.static.idStart=idStart;
dataConfig.static.counts.train=0;
dataConfig.static.counts.val=caseCount;
dataConfig.static.counts.test=0;
writeText(configPath,string(jsonencode(dataConfig)));
run_data_generation_v2("design",configPath,referenceRoot);
designPath=fullfile(referenceRoot,'static','design.csv');
freshDesign=readtable(designPath,'TextType','string');
assert(height(freshDesign)==caseCount && all(freshDesign.split=="val") && ...
    numel(unique(freshDesign.id))==caseCount, ...
    'surrogate:freshValidation:Design', ...
    'Expected exactly %d unique validation cases.',caseCount);

% Reject any accidental ID or parameter-row overlap with the original data or
% the earlier 64-case final test, before the new FEM solve begins.
oldDesigns={fullfile(projectRoot,'data_generation','data','static','design.csv'), ...
    fullfile(projectRoot,'data_generation','data','static','backup_384','design.csv'), ...
    fullfile(projectRoot,'experiments','pod_mlp_independent_test_20261106', ...
        'reference_data','static','design.csv'), ...
    fullfile(projectRoot,'experiments','pod_mlp_fresh_validation_20261108', ...
        'reference_data','static','design.csv')};
parameterNames=freshDesign.Properties.VariableNames( ...
    ~ismember(freshDesign.Properties.VariableNames,{'id','split'}));
for i=1:numel(oldDesigns)
    if isfile(oldDesigns{i})
        previous=readtable(oldDesigns{i},'TextType','string');
        assert(isempty(intersect(freshDesign.id,previous.id)) && ...
            ~any(ismember(freshDesign{:,parameterNames}, ...
            previous{:,parameterNames},'rows')), ...
            'surrogate:freshValidation:DesignOverlap', ...
            'Fresh validation design overlaps an existing design: %s',oldDesigns{i});
    end
end
writeFreezeNote(fullfile(outputDir,'FREEZE_BEFORE_LABELS.txt'), ...
    freezeMetadata, ...
    "All 420 model artifacts were frozen before reference generation. The new static validation design contains "+ ...
    string(caseCount)+" unique IDs ("+string(idStart)+"-"+string(idStart+caseCount-1)+ ...
    "), seed "+string(designSeed)+", split val only, and has no ID or exact parameter-row overlap with the known static designs.");

% This stage calculates only the 12 static validation cases; it does not
% generate training or test labels.
run_data_generation_v2("static_val",configPath,referenceRoot);
validation=surrogate.loadDataset(fullfile(referenceRoot,'static','val.mat'));
assert(string(validation.split)=="val" && numel(validation.caseIds)==caseCount, ...
    'surrogate:freshValidation:LoadedSplit', ...
    'Generated reference is not the expected %d-case validation split.',caseCount);
surrogate.validateDataset(validation);

% Evaluate all frozen models on identical inputs. Recheck each hash before
% loading it so a model cannot silently change after the freeze manifest.
request=struct('inputParameters',validation.inputParameters, ...
    'parameterNames',validation.parameterNames,'parameterUnits',validation.parameterUnits, ...
    'caseIds',validation.caseIds);
metricConfig=struct('staticReferenceFloor',0,'frequencyReferenceFloorHz',0);
runTable=emptyRunTable();
caseTable=emptyCaseTable();
for i=1:numel(modelRecords)
    record=modelRecords(i);
    assert(sha256File(record.File)==record.SHA256, ...
        'surrogate:freshValidation:ModelChanged', ...
        'Frozen model hash changed after reference generation: %s',record.File);
    model=surrogate.loadModel(record.File);
    prediction=surrogate.predictModel(model,request);
    metrics=surrogate.evaluatePrediction(prediction,validation,metricConfig);
    relative=sort(metrics.relativeWeightedFieldError(metrics.relativeErrorDefined));
    assert(numel(relative)==caseCount,'surrogate:freshValidation:RelativeCount', ...
        'Expected %d defined relative errors for %s.',caseCount,record.File);
    runRow=table(record.LossMode,record.Width,record.HiddenLayers, ...
        record.TrainingCases,record.Seed,mean(metrics.absoluteWeightedFieldError), ...
        100*median(relative),100*relative(ceil(.95*numel(relative))), ...
        'VariableNames',runTable.Properties.VariableNames);
    runTable=[runTable;runRow]; %#ok<AGROW>
    block=table(repmat(record.LossMode,caseCount,1),repmat(record.Width,caseCount,1), ...
        repmat(record.HiddenLayers,caseCount,1),repmat(record.TrainingCases,caseCount,1), ...
        repmat(record.Seed,caseCount,1),validation.caseIds, ...
        metrics.absoluteWeightedFieldError,metrics.referenceWeightedFieldNorm, ...
        metrics.relativeWeightedFieldError, ...
        'VariableNames',caseTable.Properties.VariableNames);
    caseTable=[caseTable;block]; %#ok<AGROW>
end

% Produce paired seed-aggregated architecture rows and compare losses by
% width, depth, and training count without pooling architecture families.
comparison=aggregateAndCompare(runTable,widths,depths,trainingCounts,seeds);
byTrainingCount=aggregateTrainingCounts(comparison,trainingCounts);
writetable(runTable,fullfile(outputDir,'model_metrics.csv'));
writetable(caseTable,fullfile(outputDir,'validation_case_errors.csv'));
writetable(comparison,fullfile(outputDir,'comparison_by_architecture.csv'));
writetable(byTrainingCount,fullfile(outputDir,'summary_by_training_count.csv'));
studyMetadata=struct('freeze',freezeMetadata,'validationSplit',"val", ...
    'validationIds',validation.caseIds,'validationParameters',validation.inputParameters, ...
    'referenceDatasetId',"static-fresh-validation-v1-seed"+string(designSeed)+"-n"+string(caseCount), ...
    'referenceConfig',configPath,'metricConfig',metricConfig, ...
    'testDataLoaded',false,'evaluatedModelCount',height(runTable), ...
    'caseMetricCount',height(caseTable), ...
    'createdAt',string(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ssXXX')));
save(fullfile(outputDir,'fresh_validation_comparison.mat'), ...
    'runTable','caseTable','comparison','byTrainingCount','studyMetadata','-v7.3');
result=struct('modelMetrics',runTable,'caseErrors',caseTable, ...
    'comparison',comparison,'summaryByTrainingCount',byTrainingCount, ...
    'metadata',studyMetadata);
end

function tableOut=emptyRunTable()
tableOut=table('Size',[0 8], ...
    'VariableTypes',{'string','double','double','double','double','double','double','double'}, ...
    'VariableNames',{'LossMode','Width','HiddenLayers','TrainingCases','Seed', ...
        'MeanAbsoluteErrorM','MedianRelativePercent','P95RelativePercent'});
end

function tableOut=emptyCaseTable()
tableOut=table('Size',[0 9], ...
    'VariableTypes',{'string','double','double','double','double','double','double','double','double'}, ...
    'VariableNames',{'LossMode','Width','HiddenLayers','TrainingCases','Seed', ...
        'CaseId','AbsoluteErrorM','ReferenceNormM','RelativeError'});
end

function output=aggregateAndCompare(runs,widths,depths,counts,seeds)
output=table();
for width=widths
    for depth=depths
        for count=counts
            old=runs(runs.LossMode=="per_coefficient_mse" & ...
                runs.Width==width & runs.HiddenLayers==depth & runs.TrainingCases==count,:);
            weighted=runs(runs.LossMode=="weighted_field_mse" & ...
                runs.Width==width & runs.HiddenLayers==depth & runs.TrainingCases==count,:);
            assert(height(old)==numel(seeds) && height(weighted)==numel(seeds), ...
                'surrogate:freshValidation:SeedCount', ...
                'Incomplete seed set for width %d, depth %d, n %d.',width,depth,count);
            row=table(width,depth,count,median(old.MeanAbsoluteErrorM), ...
                median(weighted.MeanAbsoluteErrorM), ...
                median(old.MedianRelativePercent),median(weighted.MedianRelativePercent), ...
                median(old.P95RelativePercent),median(weighted.P95RelativePercent), ...
                'VariableNames',{'NeuronsPerLayer','HiddenLayers','TrainingCases', ...
                    'OldLossMeanAbsoluteErrorM','WeightedLossMeanAbsoluteErrorM', ...
                    'OldLossMedianRelativePercent','WeightedLossMedianRelativePercent', ...
                    'OldLossP95RelativePercent','WeightedLossP95RelativePercent'});
            row.MedianImprovementPercentagePoints= ...
                row.OldLossMedianRelativePercent-row.WeightedLossMedianRelativePercent;
            row.P95ImprovementPercentagePoints= ...
                row.OldLossP95RelativePercent-row.WeightedLossP95RelativePercent;
            row.AbsoluteErrorImprovementM= ...
                row.OldLossMeanAbsoluteErrorM-row.WeightedLossMeanAbsoluteErrorM;
            output=[output;row]; %#ok<AGROW>
        end
    end
end
end

function output=aggregateTrainingCounts(comparison,counts)
output=table();
for count=counts
    rows=comparison(comparison.TrainingCases==count,:);
    output=[output;table(count,height(rows), ...
        mean(rows.OldLossMedianRelativePercent), ...
        mean(rows.WeightedLossMedianRelativePercent), ...
        nnz(rows.MedianImprovementPercentagePoints>0), ...
        mean(rows.OldLossP95RelativePercent), ...
        mean(rows.WeightedLossP95RelativePercent), ...
        nnz(rows.P95ImprovementPercentagePoints>0), ...
        mean(rows.OldLossMeanAbsoluteErrorM), ...
        mean(rows.WeightedLossMeanAbsoluteErrorM), ...
        nnz(rows.AbsoluteErrorImprovementM>0), ...
        'VariableNames',{'TrainingCases','ArchitectureCount', ...
            'OldLossMeanMedianPercent','WeightedLossMeanMedianPercent', ...
            'MedianImprovedArchitectures','OldLossMeanP95Percent', ...
            'WeightedLossMeanP95Percent','P95ImprovedArchitectures', ...
            'OldLossMeanAbsoluteErrorM','WeightedLossMeanAbsoluteErrorM', ...
            'AbsoluteErrorImprovedArchitectures'})]; %#ok<AGROW>
end
end

function hash=sha256File(file)
fid=fopen(file,'rb');
assert(fid>=0,'surrogate:freshValidation:HashRead','Cannot open file for hashing: %s',file);
cleanup=onCleanup(@()fclose(fid));
bytes=fread(fid,Inf,'*uint8');
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
hash=lower(string(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[])));
clear cleanup
end

function writeFreezeNote(file,metadata,details)
lines=["Frozen model comparison"; ...
    "Created before new validation labels: "+string(metadata.createdBeforeNewValidationLabels); ...
    "Models: "+string(metadata.modelCount); ...
    "Loss modes: "+strjoin(metadata.lossModes,", "); ...
    "Widths: "+join(string(metadata.widths),", "); ...
    "Hidden layers: "+join(string(metadata.depths),", "); ...
    "Training counts: "+join(string(metadata.trainingCounts),", "); ...
    "Seeds: "+join(string(metadata.seeds),", "); ...
    "Test data loaded: false"; ...
    "Details: "+details];
fid=fopen(file,'w');
assert(fid>=0,'surrogate:freshValidation:FreezeWrite','Cannot write freeze note: %s',file);
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',lines);
clear cleanup
end

function writeText(file,text)
fid=fopen(file,'w');
assert(fid>=0,'surrogate:freshValidation:Write','Cannot write file: %s',file);
cleanup=onCleanup(@()fclose(fid));
fwrite(fid,char(text),'char');
clear cleanup
end
