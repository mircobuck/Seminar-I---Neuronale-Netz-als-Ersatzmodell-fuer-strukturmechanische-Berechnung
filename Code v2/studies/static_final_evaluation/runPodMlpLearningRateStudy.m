function result = runPodMlpLearningRateStudy(outputDir)
%runPodMlpLearningRateStudy Compare fixed Adam learning rates for POD-MLP.
%   Studies rates [1e-4 3e-4 1e-3 3e-3 1e-2] at width 128, depths 1/2,
%   768 training cases, and seeds 42:44 with weighted_field_mse. Existing
%   Adam models at 1e-3 are frozen controls; the other 24 combinations are
%   newly trained. All models use the same 128 validation cases.

root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(root);
if nargin<1
    outputDir=fullfile(root,'experiments','pod_mlp_learning_rate_study_20261108');
end
assert(~isfile(outputDir),'surrogate:learningRateStudy:OutputFile', ...
    'Output path is a file: %s',outputDir);

training=surrogate.loadDataset(fullfile(root,'data_generation','data','static','train.mat'));
validationPath=fullfile(root,'experiments','pod_mlp_fresh_validation_128_20261108', ...
    'reference_data','static','val.mat');
validation=surrogate.loadDataset(validationPath);
surrogate.validateTrainingSplits(training,validation);
assert(numel(training.caseIds)>=768 && numel(validation.caseIds)==128, ...
    'surrogate:learningRateStudy:DatasetSize', ...
    'Expected at least 768 training cases and exactly 128 validation cases.');

width=128; depths=[1 2]; trainingCount=768; seeds=[42 43 44];
learningRates=[1e-4 3e-4 1e-3 3e-3 1e-2];
lossMode="weighted_field_mse"; epochs=200; batchSize=32; rank=10;
modelRoot=fullfile(root,'experiments','pod_mlp_loss_study_20261107','models');
metricConfig=struct('staticReferenceFloor',0,'frequencyReferenceFloorHz',0);
trainingIdsBySeed=cell(numel(seeds),1);
for seedIndex=1:numel(seeds)
    trainingIdsBySeed{seedIndex}=training.caseIds( ...
        trainingOrder(seeds(seedIndex),trainingCount,numel(training.caseIds)));
end
controlFiles=strings(numel(depths),numel(seeds));
controlHashes=strings(numel(depths),numel(seeds));

% Freeze and verify the existing 1e-3 Adam controls before any new fitting.
for depthIndex=1:numel(depths)
    depth=depths(depthIndex);
    for seedIndex=1:numel(seeds)
        seed=seeds(seedIndex);
        expectedIds=training.caseIds(trainingOrder(seed,trainingCount,numel(training.caseIds)));
        file=fullfile(modelRoot,sprintf( ...
            'pod_mlp_weighted_%d_width_%d_layers_n%d_seed%d.mat', ...
            width,depth,trainingCount,seed));
        assert(isfile(file),'surrogate:learningRateStudy:ControlMissing', ...
            'Missing Adam reference model: %s',file);
        model=surrogate.loadModel(file);
        assert(isequal(model.trainingCaseIds,expectedIds) && ...
            model.config.seed==seed && model.config.hiddenWidth==width && ...
            model.config.hiddenLayers==depth && model.config.rank==rank && ...
            model.config.maxEpochs==epochs && ...
            model.config.miniBatchSize==batchSize && ...
            model.config.learningRate==1e-3 && ...
            string(model.state.lossMode)==lossMode, ...
            'surrogate:learningRateStudy:ControlMismatch', ...
            'Adam reference model does not match the planned study: %s',file);
        controlFiles(depthIndex,seedIndex)=string(file);
        controlHashes(depthIndex,seedIndex)=sha256File(file);
    end
end

if ~isfolder(outputDir)
    [created,message]=mkdir(outputDir);
    assert(created,'surrogate:learningRateStudy:Directory', ...
        'Cannot create output directory: %s',message);
end

config=struct('datasetId',"static-data-generation-v1", ...
    'trainingSeeds',seeds,'trainingCaseIdsBySeed',{trainingIdsBySeed}, ...
    'validationCaseIds',validation.caseIds,'validationDataset',string(validationPath), ...
    'width',width,'depths',depths,'trainingCount',trainingCount,'seeds',seeds, ...
    'learningRates',learningRates,'lossMode',lossMode,'optimizer',"adam", ...
    'rank',rank,'maxEpochs',epochs,'miniBatchSize',batchSize, ...
    'activation',"tanh",'metricConfig',metricConfig, ...
    'testDataLoaded',false,'matlabVersion',string(version));
configPath=fullfile(outputDir,'study_config.mat');
if isfile(configPath)
    saved=load(configPath,'config');
    assert(isequaln(saved.config,config), ...
        'surrogate:learningRateStudy:ConfigMismatch', ...
        'Existing output directory belongs to a different study.');
else
    entries=dir(outputDir);
    entries=entries(~ismember({entries.name},{'.','..'}));
    assert(isempty(entries), ...
        'surrogate:learningRateStudy:UntrackedOutput', ...
        'Output directory contains files but has no matching study configuration.');
    save(configPath,'config');
end

modelDir=fullfile(outputDir,'models');
if ~isfolder(modelDir)
    [created,message]=mkdir(modelDir);
    assert(created,'surrogate:learningRateStudy:ModelDirectory', ...
        'Cannot create model directory: %s',message);
end

controlFreeze=table(repelem(depths(:),numel(seeds)), ...
    repmat(seeds(:),numel(depths),1),reshape(controlFiles.',[],1), ...
    reshape(controlHashes.',[],1), ...
    'VariableNames',{'HiddenLayers','Seed','File','SHA256'});
controlFreezePath=fullfile(outputDir,'adam_1e-3_control_freeze.csv');
if isfile(controlFreezePath)
    existing=readtable(controlFreezePath,'TextType','string');
    assert(isequal(existing,controlFreeze), ...
        'surrogate:learningRateStudy:ControlFreezeMismatch', ...
        'Saved Adam control freeze differs from the currently resolved models.');
else
    writetable(controlFreeze,controlFreezePath);
end

runPath=fullfile(outputDir,'model_metrics.csv');
casePath=fullfile(outputDir,'validation_case_errors.csv');
manifestPath=fullfile(outputDir,'model_manifest.csv');
checkpointPath=fullfile(outputDir,'learning_rate_checkpoint.mat');
if isfile(checkpointPath)
    saved=load(checkpointPath,'runTable','caseTable','records');
    runTable=saved.runTable; caseTable=saved.caseTable; records=saved.records;
else
    runTable=emptyRunTable();
    caseTable=emptyCaseTable();
    records=repmat(struct('LearningRate',0,'Depth',0,'Seed',0,'File',"", ...
        'SHA256',"",'TrainingSeconds',NaN,'IsExistingControl',false),0,1);
end

request=struct('inputParameters',validation.inputParameters, ...
    'parameterNames',validation.parameterNames,'parameterUnits',validation.parameterUnits, ...
    'caseIds',validation.caseIds);
for learningRate=learningRates
    for depth=depths
        for seed=seeds
            completed=runTable.LearningRate==learningRate & ...
                runTable.HiddenLayers==depth & runTable.Seed==seed;
            if any(completed)
                assert(nnz(completed)==1,'surrogate:learningRateStudy:DuplicateCheckpoint', ...
                    'Duplicate checkpoint for lr=%g, depth=%d, seed=%d.', ...
                    learningRate,depth,seed);
                recordIndex=find([records.LearningRate]==learningRate & ...
                    [records.Depth]==depth & [records.Seed]==seed);
                assert(isscalar(recordIndex) && ...
                    nnz(caseTable.LearningRate==learningRate & ...
                    caseTable.HiddenLayers==depth & caseTable.Seed==seed)==128 && ...
                    isfile(records(recordIndex).File) && ...
                    sha256File(records(recordIndex).File)==records(recordIndex).SHA256, ...
                    'surrogate:learningRateStudy:IncompleteCheckpoint', ...
                    'Checkpoint is incomplete or artifact hash changed.');
                continue
            end

            indices=trainingOrder(seed,trainingCount,numel(training.caseIds));
            subset=training;
            subset.caseIds=training.caseIds(indices);
            subset.inputParameters=training.inputParameters(indices,:);
            subset.displacementFields=training.displacementFields(:,indices);
            subset=rmfield(subset,{'computationTimeSeconds','tipDisplacementZ', ...
                'maxDisplacementMagnitudeOnGrid','meshNodeCounts'});
            depthIndex=find(depths==depth,1);
            seedIndex=find(seeds==seed,1);
            if learningRate==1e-3
                file=controlFiles(depthIndex,seedIndex);
                assert(sha256File(file)==controlHashes(depthIndex,seedIndex), ...
                    'surrogate:learningRateStudy:ControlChanged', ...
                    'Frozen Adam control changed during the study.');
                model=surrogate.loadModel(file);
                elapsed=NaN;
                isControl=true;
                modelHash=controlHashes(depthIndex,seedIndex);
            else
                modelName="pod_mlp_adam_lr_"+rateToken(learningRate)+ ...
                    "_width_"+string(width)+"_layers_"+string(depth)+ ...
                    "_n"+string(trainingCount)+"_seed"+string(seed)+".mat";
                file=string(fullfile(modelDir,modelName));
                modelConfig=struct('seed',seed,'datasetId',config.datasetId, ...
                    'rank',rank,'hiddenWidth',width,'maxEpochs',epochs, ...
                    'miniBatchSize',batchSize,'learningRate',learningRate, ...
                    'hiddenLayers',depth,'lossMode',lossMode,'optimizer',"adam");
                if isfile(file)
                    model=surrogate.loadModel(file);
                    assert(isequal(model.trainingCaseIds,subset.caseIds) && ...
                        isequaln(model.config,modelConfig) && ...
                        sha256File(file)==recordedHash(records,learningRate,depth,seed), ...
                        'surrogate:learningRateStudy:ArtifactConflict', ...
                        'Existing model does not match its saved checkpoint: %s',file);
                    elapsed=trainingSeconds(records,learningRate,depth,seed);
                else
                    fprintf('Adam lr %.4g, width %d, layers %d, n=%d, seed=%d\n', ...
                        learningRate,width,depth,trainingCount,seed);
                    started=tic;
                    [model,~]=surrogate.fitModel("pod_mlp",subset,modelConfig);
                    elapsed=toc(started);
                    surrogate.saveModel(file,model);
                end
                isControl=false;
                modelHash=sha256File(file);
            end

            assert(isequal(model.trainingCaseIds,subset.caseIds) && ...
                model.config.learningRate==learningRate && ...
                model.config.hiddenLayers==depth && ...
                model.config.hiddenWidth==width && ...
                model.config.maxEpochs==epochs && ...
                string(model.state.lossMode)==lossMode && ...
                (~isfield(model.config,'optimizer') || ...
                string(model.config.optimizer)=="adam"), ...
                'surrogate:learningRateStudy:ModelSettings', ...
                'Model does not match its assigned learning-rate experiment.');
            prediction=surrogate.predictModel(model,request);
            metrics=surrogate.evaluatePrediction(prediction,validation,metricConfig);
            relative=sort(metrics.relativeWeightedFieldError(metrics.relativeErrorDefined));
            assert(numel(relative)==128,'surrogate:learningRateStudy:RelativeErrors', ...
                'Expected 128 defined relative errors for every run.');
            run=table(learningRate,depth,trainingCount,seed, ...
                mean(metrics.absoluteWeightedFieldError), ...
                100*median(relative),100*relative(ceil(.95*numel(relative))), ...
                elapsed,isControl, ...
                'VariableNames',runTable.Properties.VariableNames);
            runTable=[runTable;run]; %#ok<AGROW>
            block=table(repmat(learningRate,128,1),repmat(depth,128,1), ...
                repmat(trainingCount,128,1),repmat(seed,128,1),validation.caseIds, ...
                metrics.absoluteWeightedFieldError,metrics.referenceWeightedFieldNorm, ...
                metrics.relativeWeightedFieldError, ...
                'VariableNames',caseTable.Properties.VariableNames);
            caseTable=[caseTable;block]; %#ok<AGROW>
            records(end+1,1)=struct('LearningRate',learningRate,'Depth',depth, ...
                'Seed',seed,'File',string(file),'SHA256',modelHash, ...
                'TrainingSeconds',elapsed,'IsExistingControl',isControl); %#ok<AGROW>

            writetable(runTable,runPath);
            writetable(caseTable,casePath);
            writetable(struct2table(records),manifestPath);
            save(checkpointPath,'runTable','caseTable','records','-v7.3');
        end
    end
end

assert(height(runTable)==numel(learningRates)*numel(depths)*numel(seeds) && ...
    height(caseTable)==height(runTable)*128, ...
    'surrogate:learningRateStudy:ResultCount','Incomplete learning-rate sweep.');
summary=aggregateRuns(runTable,learningRates,depths,seeds);
comparison=compareWithBaseline(summary,learningRates,depths);
overall=aggregateAcrossDepths(summary,learningRates);
writetable(summary,fullfile(outputDir,'summary_by_learning_rate.csv'));
writetable(comparison,fullfile(outputDir,'comparison_vs_1e-3.csv'));
writetable(overall,fullfile(outputDir,'summary_across_depths.csv'));
metadata=struct('config',config,'runCount',height(runTable), ...
    'caseMetricCount',height(caseTable),'validationCaseCount',128, ...
    'reusedAdamControlCount',nnz(runTable.IsExistingControl), ...
    'newlyTrainedRunCount',nnz(~runTable.IsExistingControl), ...
    'testDataLoaded',false, ...
    'createdAt',string(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ssXXX')));
save(fullfile(outputDir,'learning_rate_results.mat'), ...
    'runTable','caseTable','records','summary','comparison','overall','metadata','-v7.3');
result=struct('modelMetrics',runTable,'caseErrors',caseTable, ...
    'summaryByLearningRate',summary,'comparisonVsBaseline',comparison, ...
    'summaryAcrossDepths',overall,'metadata',metadata);
end

function indices=trainingOrder(seed,count,totalCount)
originalCount=min(384,totalCount);
stream=RandStream('mt19937ar','Seed',seed);
order=[randperm(stream,originalCount), ...
    originalCount+randperm(stream,totalCount-originalCount)];
indices=order(1:count);
end

function token=rateToken(rate)
token=replace(string(sprintf('%.0e',rate)),'-','m');
token=replace(token,'+','p');
end

function tableOut=emptyRunTable()
tableOut=table('Size',[0 9], ...
    'VariableTypes',{'double','double','double','double','double','double', ...
    'double','double','logical'}, ...
    'VariableNames',{'LearningRate','HiddenLayers','TrainingCases','Seed', ...
    'MeanAbsoluteErrorM','MedianRelativePercent','P95RelativePercent', ...
    'TrainingSeconds','IsExistingControl'});
end

function tableOut=emptyCaseTable()
tableOut=table('Size',[0 8], ...
    'VariableTypes',{'double','double','double','double','double','double','double','double'}, ...
    'VariableNames',{'LearningRate','HiddenLayers','TrainingCases','Seed', ...
    'CaseId','AbsoluteErrorM','ReferenceNormM','RelativeError'});
end

function output=aggregateRuns(runs,rates,depths,seeds)
output=table();
for rate=rates
    for depth=depths
        rows=runs(runs.LearningRate==rate & runs.HiddenLayers==depth,:);
        assert(height(rows)==numel(seeds),'surrogate:learningRateStudy:SeedCount', ...
            'Incomplete seeds for learning rate %g and depth %d.',rate,depth);
        output=[output;table(rate,depth,median(rows.MeanAbsoluteErrorM), ...
            median(rows.MedianRelativePercent),median(rows.P95RelativePercent), ...
            mean(rows.MeanAbsoluteErrorM),std(rows.MeanAbsoluteErrorM), ...
            'VariableNames',{'LearningRate','HiddenLayers', ...
            'MedianSeedMeanAbsoluteErrorM','MedianRelativePercent','P95RelativePercent', ...
            'MeanSeedMeanAbsoluteErrorM','StdSeedMeanAbsoluteErrorM'})]; %#ok<AGROW>
    end
end
end

function output=compareWithBaseline(summary,rates,depths)
output=table();
for depth=depths
    baseline=summary(summary.LearningRate==1e-3 & summary.HiddenLayers==depth,:);
    for rate=rates(rates~=1e-3)
        candidate=summary(summary.LearningRate==rate & summary.HiddenLayers==depth,:);
        assert(height(baseline)==1 && height(candidate)==1, ...
            'surrogate:learningRateStudy:ComparisonRows', ...
            'Missing learning-rate comparison row.');
        output=[output;table(rate,depth,baseline.MedianSeedMeanAbsoluteErrorM, ...
            candidate.MedianSeedMeanAbsoluteErrorM,baseline.MedianRelativePercent, ...
            candidate.MedianRelativePercent,baseline.P95RelativePercent, ...
            candidate.P95RelativePercent, ...
            baseline.MedianSeedMeanAbsoluteErrorM-candidate.MedianSeedMeanAbsoluteErrorM, ...
            baseline.MedianRelativePercent-candidate.MedianRelativePercent, ...
            baseline.P95RelativePercent-candidate.P95RelativePercent, ...
            'VariableNames',{'LearningRate','HiddenLayers','BaselineMeanAbsoluteErrorM', ...
            'CandidateMeanAbsoluteErrorM','BaselineMedianRelativePercent', ...
            'CandidateMedianRelativePercent','BaselineP95RelativePercent', ...
            'CandidateP95RelativePercent','AbsoluteErrorImprovementM', ...
            'MedianImprovementPercentagePoints','P95ImprovementPercentagePoints'})]; %#ok<AGROW>
    end
end
end

function output=aggregateAcrossDepths(summary,rates)
output=table();
for rate=rates
    rows=summary(summary.LearningRate==rate,:);
    assert(height(rows)==2,'surrogate:learningRateStudy:DepthCount', ...
        'Expected both network depths for learning rate %g.',rate);
    output=[output;table(rate,mean(rows.MedianSeedMeanAbsoluteErrorM), ...
        mean(rows.MedianRelativePercent),mean(rows.P95RelativePercent), ...
        'VariableNames',{'LearningRate','MeanAcrossDepthsAbsoluteErrorM', ...
        'MeanAcrossDepthsMedianRelativePercent','MeanAcrossDepthsP95RelativePercent'})]; %#ok<AGROW>
end
end

function hash=recordedHash(records,rate,depth,seed)
index=find([records.LearningRate]==rate & [records.Depth]==depth & [records.Seed]==seed,1);
assert(~isempty(index),'surrogate:learningRateStudy:UntrackedArtifact', ...
    'An existing model has no matching checkpoint record.');
hash=records(index).SHA256;
end

function seconds=trainingSeconds(records,rate,depth,seed)
index=find([records.LearningRate]==rate & [records.Depth]==depth & [records.Seed]==seed,1);
assert(~isempty(index),'surrogate:learningRateStudy:UntrackedArtifact', ...
    'An existing model has no matching checkpoint record.');
seconds=records(index).TrainingSeconds;
end

function hash=sha256File(file)
fid=fopen(file,'rb');
assert(fid>=0,'surrogate:learningRateStudy:HashRead', ...
    'Cannot open model for hashing: %s',file);
cleanup=onCleanup(@()fclose(fid));
bytes=fread(fid,Inf,'*uint8');
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
hash=lower(string(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[])));
clear cleanup
end
