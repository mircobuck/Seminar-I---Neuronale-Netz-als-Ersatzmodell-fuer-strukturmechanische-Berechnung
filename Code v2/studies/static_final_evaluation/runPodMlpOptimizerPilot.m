function result = runPodMlpOptimizerPilot(outputDir)
%runPodMlpOptimizerPilot Compare RMSProp and SGDM with the weighted POD-MLP loss.
%   Trains width-128, depth-1/2 models on 768 cases with seeds 42:44.
%   Existing weighted-loss Adam models are the control. All models are
%   evaluated on the same 128 fresh validation cases. The output folder must
%   not exist; this is an exploratory optimizer comparison, not a final test.

root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(root);
if nargin<1
    outputDir=fullfile(root,'experiments','pod_mlp_optimizer_pilot_20261108');
end
assert(~isfolder(outputDir) && ~isfile(outputDir), ...
    'surrogate:optimizerPilot:Exists','Output path already exists: %s',outputDir);

training=surrogate.loadDataset(fullfile(root,'data_generation','data','static','train.mat'));
validation=surrogate.loadDataset(fullfile(root, ...
    'experiments','pod_mlp_fresh_validation_128_20261108', ...
    'reference_data','static','val.mat'));
surrogate.validateTrainingSplits(training,validation);
assert(numel(training.caseIds)>=768 && numel(validation.caseIds)==128, ...
    'surrogate:optimizerPilot:DatasetSize', ...
    'Expected at least 768 training cases and exactly 128 fresh validation cases.');

width=128; depths=[1 2]; trainingCount=768; seeds=[42 43 44];
optimizers=["adam","rmsprop","sgdm"];
lossMode="weighted_field_mse";
epochs=200; batchSize=32; learningRate=1e-3; rank=10;
modelCount=numel(optimizers)*numel(depths)*numel(seeds);
modelRoot=fullfile(root,'experiments','pod_mlp_loss_study_20261107','models');
controlFiles=strings(numel(depths),numel(seeds));
controlHashes=strings(numel(depths),numel(seeds));
for depthIndex=1:numel(depths)
    depth=depths(depthIndex);
    for seedIndex=1:numel(seeds)
        seed=seeds(seedIndex);
        indices=trainingOrder(seed,trainingCount,numel(training.caseIds));
        expectedIds=training.caseIds(indices);
        controlFile=fullfile(modelRoot,sprintf( ...
            'pod_mlp_weighted_%d_width_%d_layers_n%d_seed%d.mat', ...
            width,depth,trainingCount,seed));
        assert(isfile(controlFile),'surrogate:optimizerPilot:AdamMissing', ...
            'Missing existing Adam control: %s',controlFile);
        control=surrogate.loadModel(controlFile);
        assert(isequal(control.trainingCaseIds,expectedIds) && ...
            control.config.seed==seed && control.config.hiddenWidth==width && ...
            control.config.hiddenLayers==depth && control.config.rank==rank && ...
            control.config.maxEpochs==epochs && ...
            control.config.miniBatchSize==batchSize && ...
            control.config.learningRate==learningRate && ...
            string(control.state.lossMode)==lossMode, ...
            'surrogate:optimizerPilot:AdamMismatch', ...
            'Adam control does not match the requested training setup: %s',controlFile);
        controlFiles(depthIndex,seedIndex)=string(controlFile);
        controlHashes(depthIndex,seedIndex)=sha256File(controlFile);
    end
end
modelDir=fullfile(outputDir,'models');
[created,message]=mkdir(outputDir);
assert(created,'surrogate:optimizerPilot:Directory', ...
    'Cannot create output directory: %s',message);
[created,message]=mkdir(modelDir);
assert(created,'surrogate:optimizerPilot:Directory', ...
    'Cannot create output directory: %s',message);

config=struct('datasetId',"static-data-generation-v1", ...
    'trainingCaseIds',training.caseIds,'validationCaseIds',validation.caseIds, ...
    'width',width,'depths',depths,'trainingCount',trainingCount, ...
    'seeds',seeds,'optimizers',optimizers,'lossMode',lossMode, ...
    'rank',rank,'maxEpochs',epochs,'miniBatchSize',batchSize, ...
    'learningRate',learningRate,'activation',"tanh", ...
    'metricConfig',struct('staticReferenceFloor',0,'frequencyReferenceFloorHz',0), ...
    'testDataLoaded',false,'matlabVersion',string(version));
save(fullfile(outputDir,'pilot_config.mat'),'config');
adamFreeze=table(repelem(depths(:),numel(seeds)), ...
    repmat(seeds(:),numel(depths),1),reshape(controlFiles.',[],1), ...
    reshape(controlHashes.',[],1), ...
    'VariableNames',{'HiddenLayers','Seed','File','SHA256'});
writetable(adamFreeze,fullfile(outputDir,'adam_control_freeze.csv'));
records=repmat(struct('Optimizer',"",'Depth',0,'Seed',0,'File',"", ...
    'SHA256',"",'TrainingSeconds',NaN,'IsExistingAdamControl',false),modelCount,1);
runTable=table('Size',[0 8], ...
    'VariableTypes',{'string','double','double','double','double','double','double','double'}, ...
    'VariableNames',{'Optimizer','HiddenLayers','TrainingCases','Seed', ...
    'MeanAbsoluteErrorM','MedianRelativePercent','P95RelativePercent','TrainingSeconds'});
caseTable=table('Size',[0 8], ...
    'VariableTypes',{'string','double','double','double','double','double','double','double'}, ...
    'VariableNames',{'Optimizer','HiddenLayers','TrainingCases','Seed', ...
    'CaseId','AbsoluteErrorM','ReferenceNormM','RelativeError'});

request=struct('inputParameters',validation.inputParameters, ...
    'parameterNames',validation.parameterNames,'parameterUnits',validation.parameterUnits, ...
    'caseIds',validation.caseIds);
metricConfig=config.metricConfig;
recordIndex=0;
for depth=depths
    for seed=seeds
        indices=trainingOrder(seed,trainingCount,numel(training.caseIds));
        subset=training;
        subset.caseIds=training.caseIds(indices);
        subset.inputParameters=training.inputParameters(indices,:);
        subset.displacementFields=training.displacementFields(:,indices);
        subset=rmfield(subset,{'computationTimeSeconds','tipDisplacementZ', ...
            'maxDisplacementMagnitudeOnGrid','meshNodeCounts'});

        controlFile=fullfile(modelRoot,sprintf( ...
            'pod_mlp_weighted_%d_width_%d_layers_n%d_seed%d.mat', ...
            width,depth,trainingCount,seed));
        depthIndex=find(depths==depth,1);
        seedIndex=find(seeds==seed,1);
        assert(isfile(controlFile) && ...
            sha256File(controlFile)==controlHashes(depthIndex,seedIndex), ...
            'surrogate:optimizerPilot:AdamChanged', ...
            'Adam control changed after its freeze: %s',controlFile);
        control=surrogate.loadModel(controlFile);
        assert(isequal(control.trainingCaseIds,subset.caseIds), ...
            'surrogate:optimizerPilot:TrainingIds', ...
            'Adam and candidate model use different training IDs.');

        for optimizer=optimizers
            if optimizer=="adam"
                model=control;
                modelFile=string(controlFile);
                modelHash=controlHashes(depthIndex,seedIndex);
                elapsed=NaN;
                existingControl=true;
            else
                modelConfig=struct('seed',seed,'datasetId',config.datasetId, ...
                    'rank',rank,'hiddenWidth',width,'maxEpochs',epochs, ...
                    'miniBatchSize',batchSize,'learningRate',learningRate, ...
                    'hiddenLayers',depth,'lossMode',lossMode,'optimizer',optimizer);
                modelName="pod_mlp_"+optimizer+"_width_"+string(width)+ ...
                    "_layers_"+string(depth)+"_n"+string(trainingCount)+ ...
                    "_seed"+string(seed)+".mat";
                modelFile=string(fullfile(modelDir,modelName));
                fprintf('Training %s: width %d, layers %d, cases %d, seed %d\n', ...
                    char(optimizer),width,depth,trainingCount,seed);
                started=tic;
                [model,report]=surrogate.fitModel("pod_mlp",subset,modelConfig);
                elapsed=toc(started);
                assert(string(report.optimizer)==optimizer && ...
                    string(model.state.lossMode)==lossMode, ...
                    'surrogate:optimizerPilot:TrainingSettings', ...
                    'Fitted model did not retain the requested optimizer/loss.');
                surrogate.saveModel(modelFile,model);
                modelHash=sha256File(modelFile);
                existingControl=false;
            end

            prediction=surrogate.predictModel(model,request);
            metrics=surrogate.evaluatePrediction(prediction,validation,metricConfig);
            relative=sort(metrics.relativeWeightedFieldError(metrics.relativeErrorDefined));
            assert(numel(relative)==numel(validation.caseIds), ...
                'surrogate:optimizerPilot:RelativeErrors', ...
                'Expected a defined relative error for every validation case.');
            run=table(optimizer,depth,trainingCount,seed, ...
                mean(metrics.absoluteWeightedFieldError), ...
                100*median(relative),100*relative(ceil(.95*numel(relative))),elapsed, ...
                'VariableNames',runTable.Properties.VariableNames);
            runTable=[runTable;run]; %#ok<AGROW>
            block=table(repmat(optimizer,numel(validation.caseIds),1), ...
                repmat(depth,numel(validation.caseIds),1), ...
                repmat(trainingCount,numel(validation.caseIds),1), ...
                repmat(seed,numel(validation.caseIds),1),validation.caseIds, ...
                metrics.absoluteWeightedFieldError,metrics.referenceWeightedFieldNorm, ...
                metrics.relativeWeightedFieldError, ...
                'VariableNames',caseTable.Properties.VariableNames);
            caseTable=[caseTable;block]; %#ok<AGROW>

            recordIndex=recordIndex+1;
            records(recordIndex)=struct('Optimizer',optimizer,'Depth',depth, ...
                'Seed',seed,'File',modelFile,'SHA256',modelHash, ...
                'TrainingSeconds',elapsed,'IsExistingAdamControl',existingControl);
            writetable(runTable,fullfile(outputDir,'model_metrics.csv'));
            writetable(caseTable,fullfile(outputDir,'validation_case_errors.csv'));
            writetable(struct2table(records(1:recordIndex)), ...
                fullfile(outputDir,'model_manifest.csv'));
            save(fullfile(outputDir,'optimizer_pilot_checkpoint.mat'), ...
                'runTable','caseTable','records','config','-v7.3');
        end
    end
end
assert(recordIndex==modelCount,'surrogate:optimizerPilot:ModelCount', ...
    'Expected %d optimizer/architecture/seed combinations.',modelCount);

summary=aggregateRuns(runTable,depths,optimizers,seeds);
comparison=compareWithAdam(summary,depths);
writetable(summary,fullfile(outputDir,'summary_by_optimizer.csv'));
writetable(comparison,fullfile(outputDir,'optimizer_comparison.csv'));
metadata=struct('config',config,'evaluatedModelCount',height(runTable), ...
    'caseMetricCount',height(caseTable),'validationCaseCount',numel(validation.caseIds), ...
    'modelHashesRecorded',true,'testDataLoaded',false, ...
    'createdAt',string(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ssXXX')));
save(fullfile(outputDir,'optimizer_pilot_results.mat'), ...
    'runTable','caseTable','summary','comparison','records','metadata','-v7.3');
result=struct('modelMetrics',runTable,'caseErrors',caseTable, ...
    'summaryByOptimizer',summary,'comparison',comparison,'metadata',metadata);
end

function indices=trainingOrder(seed,count,totalCount)
originalCount=min(384,totalCount);
stream=RandStream('mt19937ar','Seed',seed);
order=[randperm(stream,originalCount), ...
    originalCount+randperm(stream,totalCount-originalCount)];
indices=order(1:count);
end

function output=aggregateRuns(runs,depths,optimizers,seeds)
output=table();
for depth=depths
    for optimizer=optimizers
        rows=runs(runs.HiddenLayers==depth & runs.Optimizer==optimizer,:);
        assert(height(rows)==numel(seeds),'surrogate:optimizerPilot:SeedCount', ...
            'Incomplete seed set for optimizer %s, depth %d.',optimizer,depth);
        output=[output;table(optimizer,depth,median(rows.MeanAbsoluteErrorM), ...
            median(rows.MedianRelativePercent),median(rows.P95RelativePercent), ...
            mean(rows.MeanAbsoluteErrorM),std(rows.MeanAbsoluteErrorM), ...
            'VariableNames',{'Optimizer','HiddenLayers','MedianSeedMeanAbsoluteErrorM', ...
            'MedianRelativePercent','P95RelativePercent','MeanSeedMeanAbsoluteErrorM', ...
            'StdSeedMeanAbsoluteErrorM'})]; %#ok<AGROW>
    end
end
end

function output=compareWithAdam(summary,depths)
output=table();
for depth=depths
    control=summary(summary.HiddenLayers==depth & summary.Optimizer=="adam",:);
    for optimizer=["rmsprop","sgdm"]
        candidate=summary(summary.HiddenLayers==depth & summary.Optimizer==optimizer,:);
        assert(height(control)==1 && height(candidate)==1, ...
            'surrogate:optimizerPilot:ComparisonRows', ...
            'Missing comparison row for optimizer %s, depth %d.',optimizer,depth);
        output=[output;table(optimizer,depth, ...
            control.MedianSeedMeanAbsoluteErrorM,candidate.MedianSeedMeanAbsoluteErrorM, ...
            control.MedianRelativePercent,candidate.MedianRelativePercent, ...
            control.P95RelativePercent,candidate.P95RelativePercent, ...
            control.MeanSeedMeanAbsoluteErrorM-candidate.MeanSeedMeanAbsoluteErrorM, ...
            control.MedianRelativePercent-candidate.MedianRelativePercent, ...
            control.P95RelativePercent-candidate.P95RelativePercent, ...
            'VariableNames',{'Optimizer','HiddenLayers','AdamMeanAbsoluteErrorM', ...
            'CandidateMeanAbsoluteErrorM','AdamMedianRelativePercent', ...
            'CandidateMedianRelativePercent','AdamP95RelativePercent', ...
            'CandidateP95RelativePercent','AbsoluteErrorImprovementM', ...
            'MedianImprovementPercentagePoints','P95ImprovementPercentagePoints'})]; %#ok<AGROW>
    end
end
end

function hash=sha256File(file)
fid=fopen(file,'rb');
assert(fid>=0,'surrogate:optimizerPilot:HashRead','Cannot open model for hashing: %s',file);
cleanup=onCleanup(@()fclose(fid));
bytes=fread(fid,Inf,'*uint8');
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
hash=lower(string(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[])));
clear cleanup
end
