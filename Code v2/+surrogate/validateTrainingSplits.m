function validateTrainingSplits(trainingData,validationData)
%validateTrainingSplits Check training and validation data are disjoint.
%   Expects contract data from surrogate.loadDataset or validateDataset.
assert(string(trainingData.split)=="train" && string(validationData.split)=="val" && ...
    string(trainingData.modality)=="static" && string(validationData.modality)=="static", ...
    'surrogate:splits:Role','Expected training and validation splits of the same task.');
assert(isempty(intersect(trainingData.caseIds,validationData.caseIds)) && ...
    ~any(ismember(trainingData.inputParameters,validationData.inputParameters,'rows')), ...
    'surrogate:splits:Overlap','Training and validation cases or parameter rows overlap.');
assert(isequal(trainingData.normalizedGridCoordinates,validationData.normalizedGridCoordinates) && ...
    isequal(trainingData.displacementComponentWeights,validationData.displacementComponentWeights), ...
    'surrogate:splits:Grid','Training and validation grids or weights differ.');
end
