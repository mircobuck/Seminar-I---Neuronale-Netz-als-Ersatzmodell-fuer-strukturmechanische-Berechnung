function model = loadModel(filePath)
%loadModel Load a saved model artifact.
loaded=load(filePath,'model');
assert(isfield(loaded,'model') && isstruct(loaded.model) && ...
    isscalar(loaded.model) && all(isfield(loaded.model, ...
    {'contractVersion','methodId','task','parameterNames','parameterUnits', ...
    'outputUnit','config','trainingCaseIds','matlabVersion','state'})), ...
    'surrogate:load:Model','Incomplete model artifact.');
model=loaded.model;
end
