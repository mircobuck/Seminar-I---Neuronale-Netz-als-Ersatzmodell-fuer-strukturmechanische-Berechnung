function validateDataset(data)
%validateDataset Check the common data contract for one split.
required = {'contractVersion','modality','split','caseIds', ...
    'inputParameters','parameterNames','parameterUnits'};
assert(isstruct(data) && isscalar(data) && all(isfield(data,required)), ...
    'surrogate:data:Fields','Missing required dataset fields.');
c = surrogate.contract(data.modality);
assert(isequal(string(data.contractVersion),c.version), ...
    'surrogate:data:Version','Unsupported contract version.');
assert(isscalar(string(data.split)) && any(string(data.split)==["train","val","test"]), ...
    'surrogate:data:Split','Invalid split.');
assert(isequal(reshape(string(data.parameterNames),1,[]),c.parameterNames) && ...
    isequal(reshape(string(data.parameterUnits),1,[]),c.parameterUnits), ...
    'surrogate:data:Parameters','Parameter names, order or units differ.');
X=data.inputParameters;
assert(isnumeric(X) && isreal(X) && ismatrix(X) && size(X,2)==6 && ...
    size(X,1)>0 && all(isfinite(X),'all'), ...
    'surrogate:data:Inputs','Inputs must be a finite N-by-6 matrix.');
n=size(X,1); ids=data.caseIds;
assert(isnumeric(ids) && isreal(ids) && isequal(size(ids),[n,1]) && ...
    all(isfinite(ids)) && all(ids==fix(ids)) && numel(unique(ids))==n, ...
    'surrogate:data:Ids','Case IDs must be unique finite integers in an N-by-1 vector.');
if c.task=="static"
    assert(all(isfield(data,{'displacementFields','normalizedGridCoordinates', ...
        'displacementComponentWeights'})), 'surrogate:data:Fields', ...
        'Static data requires fields, grid and weights.');
    assert(isnumeric(data.displacementFields) && isreal(data.displacementFields) && ...
        isequal(size(data.displacementFields),[1575,n]) && ...
        all(isfinite(data.displacementFields),'all'), ...
        'surrogate:data:Targets','Static fields must be finite 1575-by-N.');
    assert(isequal(size(data.normalizedGridCoordinates),[3,525]) && ...
        max(abs(data.normalizedGridCoordinates-c.grid),[],'all')<1e-12, ...
        'surrogate:data:Grid','Grid or grid ordering differs from contract.');
    w=data.displacementComponentWeights;
    assert(isnumeric(w) && isreal(w) && isequal(size(w),[1575,1]) && ...
        all(isfinite(w)) && all(w>0), 'surrogate:data:Weights', ...
        'Weights must be finite positive 1575-by-1 values.');
else
    assert(isfield(data,'naturalFrequenciesHz') && ...
        isnumeric(data.naturalFrequenciesHz) && isreal(data.naturalFrequenciesHz) && ...
        isequal(size(data.naturalFrequenciesHz),[n,6]) && ...
        all(isfinite(data.naturalFrequenciesHz),'all'), ...
        'surrogate:data:Targets','Modal targets must be finite N-by-6.');
    assert(isfield(data,'frequencyUnit') && string(data.frequencyUnit)=="Hz" && ...
        isfield(data,'modeIndices') && isequal(data.modeIndices(:),(1:6)'), ...
        'surrogate:data:FrequencyMetadata','Frequency unit or mode indices differ.');
end
end
