function result = evaluateFrequencies(prediction,reference)
%evaluateFrequencies Rank-aligned errors, without sorting or clipping predictions.
surrogate.validateDataset(reference);
c=surrogate.contract("modal");
assert(string(prediction.contractVersion)==c.version && string(prediction.task)==c.task && ...
    string(prediction.outputUnit)==c.outputUnit && isequal(prediction.modeIndices,c.modeIndices), ...
    'surrogate:evaluate:Prediction','Frequency metadata differs from reference.');
assert(isequal(prediction.caseIds,reference.caseIds),'surrogate:evaluate:CaseIds','Case IDs or order differ.');
F=prediction.frequencyHz; R=reference.frequencyHz;
assert(isnumeric(F) && isreal(F) && isequal(size(F),size(R)) && all(isfinite(F),'all'), ...
    'surrogate:evaluate:Output','Invalid frequency prediction.');
absolute=abs(F-R); relative=absolute./R;
result=struct('contractVersion',c.version,'task',c.task,'split',string(reference.split), ...
    'caseIds',reference.caseIds,'absoluteFrequencyErrorHz',absolute, ...
    'relativeFrequencyError',relative,'meanRelativeErrorPerCase',mean(relative,2), ...
    'nonpositiveFrequency',F<=0,'orderViolation',any(diff(F,1,2)<0,2));
end
