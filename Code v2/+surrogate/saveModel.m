function saveModel(filePath,model)
%saveModel Save an artifact without intentionally replacing an existing file.
assert(~isfile(filePath),'surrogate:save:Exists','File already exists: %s',filePath);
assert(isstruct(model) && isscalar(model) && all(isfield(model, ...
    {'contractVersion','methodId','task','parameterNames','parameterUnits', ...
    'outputUnit','config','trainingCaseIds','matlabVersion','state'})), ...
    'surrogate:save:Model','Incomplete model artifact.');
parent=fileparts(filePath);
assert(isempty(parent) || isfolder(parent),'surrogate:save:Directory', ...
    'Target directory does not exist.');
save(filePath,'model','-v7.3');
end
