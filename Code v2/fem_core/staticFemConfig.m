function settings = staticFemConfig(study)
%staticFemConfig Derive only physical solver settings from the current study.
settings=struct('gridSize',[21 5 5], ...
    'meshDivisor',study.mesh_divisor, ...
    'geometricOrder',string(study.geometric_order), ...
    'saveRawMesh',false, ...
    'maxDeflectionRatio',study.max_deflection_ratio);
end
